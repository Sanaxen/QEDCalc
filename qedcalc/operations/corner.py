def corner_outer_stream_denominators(u=None,v=None,rho=None,a_d=None,a_l=None,z=None):
    """Generate the completed outer denominators for all three streams.

    The outer denominators are photon K, two coincident electron denominators D,
    and, when present, Lambda' or Lambda_z.  The returned Q forms include the
    finite photon mass and reduce to the v0.58 H/Q and H_z/Q_z polynomials at
    rho=0.
    """
    u=sp.Symbol('u', positive=True) if u is None else sp.sympify(u)
    v=sp.Symbol('v', real=True) if v is None else sp.sympify(v)
    rho=sp.Symbol('rho', positive=True) if rho is None else sp.sympify(rho)
    ad=sp.Symbol('a_d', nonnegative=True) if a_d is None else sp.sympify(a_d)
    al=sp.Symbol('a_l', nonnegative=True) if a_l is None else sp.sympify(a_l)
    zz=sp.Symbol('z_inner', real=True) if z is None else sp.sympify(z)
    ap=sp.expand(1-ad-al)
    L0=sp.expand(u**2+rho**2*(1-u))
    A=sp.expand(u*v*(1-u*v))
    C=sp.expand(u*v*(1-u))

    H=sp.expand(1-al+al*A)
    B=sp.expand(ad+al*C)
    const=sp.expand(ap*rho**2+al*L0)
    Q=sp.expand(B**2+H*const)

    Hz=sp.expand(1-al+al*zz*A)
    Bz=sp.expand(ad+al*zz*C)
    constz=sp.expand(ap*rho**2+al*L0)
    Qz=sp.expand(Bz**2+Hz*constz)

    # Lambda0 is independent of outer k, hence the last stream only contains
    # K*D^2.  With a_p=1-a_d its completed quadratic is Q0.
    Q0=sp.expand(ad**2+(1-ad)*rho**2)
    delta=sp.Symbol('k2')*A-2*sp.Symbol('pk')*C
    return CornerOuterStreamDenominators(H,B,Q,Hz,Bz,Qz,Q0,L0,delta)


