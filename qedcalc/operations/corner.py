@dataclass(frozen=True)
class CornerGaussianBareTemplates:
    """Loop-momentum integrated bare corner kernels before parameter substitution.

    ``G4`` and ``G5`` are expressed through the compact quadratic-form symbols
    ``a,b,c,r,s,Delta,Phi`` together with the simplex parameters ``x,y,z``.
    The common Jacobian ``1/Delta**2`` and the conversion to the
    ``(alpha/pi)**2`` normalization are already included.
    """
    G4: sp.Expr
    G5: sp.Expr
    base4_radial: sp.Expr
    base5_radial: sp.Expr
    denominator4_radial: tuple
    denominator5_radial: sp.Expr


def _corner_streaming_moment(indices):
    metric=(1,-1,-1,-1)
    n=len(indices)
    if n == 0:
        return sp.Integer(1)
    if n % 2:
        return sp.Integer(0)
    if n == 2:
        i,j=indices
        return sp.Rational(1,4)*metric[i] if i == j else sp.Integer(0)
    if n == 4:
        i,j,k,l=indices
        def g(p,q):
            return metric[p] if p == q else sp.Integer(0)
        return sp.Rational(1,24)*(g(i,j)*g(k,l)+g(i,k)*g(j,l)+g(i,l)*g(j,k))
    raise ValueError(f"Corner streaming reduction encountered rank {n}; expected <=4.")


def _corner_streaming_reduce_shifted_polynomial(expr):
    """Shift k,l to independent P,Q and immediately apply isotropic moments.

    This deliberately processes one k/l monomial at a time.  It avoids the
    very large intermediate Dirac/P/Q polynomial produced by the historical
    monolithic SymPy script.
    """
    a,b,c,r,s,Delta=sp.symbols('a b c r s Delta', nonzero=True)
    P=sp.symbols('cP0:4'); Q=sp.symbols('cQ0:4')
    Ps,Qs=sp.symbols('cPs cQs')
    ck=sp.symbols('ck0:4'); cl=sp.symbols('cl0:4')
    eta=(b*r-c*s)/Delta
    xi=(a*s-c*r)/Delta
    Ak=sp.sqrt(b/Delta)
    cp=c/sp.sqrt(b*Delta)
    iq=1/sp.sqrt(b)
    kval=(eta+Ak*P[0],Ak*P[1],Ak*P[2],Ak*P[3])
    lval=(xi-cp*P[0]+iq*Q[0],-cp*P[1]+iq*Q[1],-cp*P[2]+iq*Q[2],-cp*P[3]+iq*Q[3])
    allvars=P+Q

    def reduce_one(term):
        poly=sp.Poly(sp.expand(term),*allvars,domain='EX')
        ans=sp.Integer(0)
        for powers,coef in poly.terms():
            pinds=[]; qinds=[]
            for j,n in enumerate(powers[:4]):
                pinds.extend([j]*n)
            for j,n in enumerate(powers[4:]):
                qinds.extend([j]*n)
            mp=_corner_streaming_moment(pinds)
            mq=_corner_streaming_moment(qinds)
            if mp == 0 or mq == 0:
                continue
            ans += coef*mp*mq*Ps**(len(pinds)//2)*Qs**(len(qinds)//2)
        return ans

    source=sp.Poly(expr,*ck,*cl,domain='EX')
    out=sp.Integer(0)
    for powers,coef in source.terms():
        term=coef
        for j,n in enumerate(powers[:4]):
            term *= kval[j]**n
        for j,n in enumerate(powers[4:]):
            term *= lval[j]**n
        out += reduce_one(term)
    # Resolve products such as sqrt(b/Delta)*sqrt(Delta*b) under the
    # positive Feynman-parameter domain before radial integration.
    return sp.cancel(sp.powdenest(out,force=True))


def _corner_streaming_radial_integral(expr,n):
    """Perform the two independent four-dimensional Euclidean radial moments."""
    Phi=sp.Symbol('Phi', nonzero=True)
    Ps,Qs=sp.symbols('cPs cQs')
    poly=sp.Poly(sp.expand(expr),Ps,Qs,domain='EX')
    out=sp.Integer(0)
    for (rp,rq),coef in poly.terms():
        arg=n-rp-rq-4
        if arg <= 0:
            # A magnetic projection must remove the apparent overall Gamma(0)
            # sector before this stage.  Keep the failure explicit.
            raise ValueError(f"Uncancelled corner radial UV pole: n={n}, ranks={(rp,rq)}")
        radial=(
            (-1)**(rp+rq)
            * sp.factorial(rp+1)*sp.factorial(rq+1)
            * sp.gamma(arg)/sp.gamma(n)
            * Phi**(rp+rq+4-n)
        )
        out += coef*radial
    return sp.cancel(out)


@lru_cache(maxsize=1)
def corner_gaussian_bare_templates() -> CornerGaussianBareTemplates:
    """Generate both bare corner parameter kernels from the raw projector.

    The split parameter has already been integrated after q differentiation.
    For diagram 5 this gives ``<t>=1/2``.  For diagram 4 it produces the
    three denominator-derivative streams proportional to k, k+l, and l.
    """
    rproj=corner_raw_projector_polynomials()
    ck=sp.symbols('ck0:4'); cl=sp.symbols('cl0:4')
    x,y,z=sp.symbols('x y z')
    Delta=sp.Symbol('Delta', nonzero=True)

    red5=_corner_streaming_reduce_shifted_polynomial(rproj.diagram5_base)
    den5=_corner_streaming_reduce_shifted_polynomial(-ck[1]*rproj.diagram5_transverse_zero)
    I5=_corner_streaming_radial_integral(red5,6)
    I5k=_corner_streaming_radial_integral(den5,7)

    red4=_corner_streaming_reduce_shifted_polynomial(rproj.diagram4_base)
    den4k=_corner_streaming_reduce_shifted_polynomial(-ck[1]*rproj.diagram4_transverse_zero)
    den4kl=_corner_streaming_reduce_shifted_polynomial(-(ck[1]+cl[1])*rproj.diagram4_transverse_zero)
    den4l=_corner_streaming_reduce_shifted_polynomial(-cl[1]*rproj.diagram4_transverse_zero)
    I4=_corner_streaming_radial_integral(red4,6)
    I4k=_corner_streaming_radial_integral(den4k,7)
    I4kl=_corner_streaming_radial_integral(den4kl,7)
    I4l=_corner_streaming_radial_integral(den4l,7)

    # Breit-projector denominator derivative:
    # 2 i[-6 dD/dq] N_2^(0).  Integrating the split parameter t gives
    # diagram 5:  -1440 i x^2 (q.k) N_2^(0),
    # diagram 4:  -2880 i z[x(q.k)+y q.(k+l)+z/2(q.l)] N_2^(0).
    # The common 1/(16 Delta^2) is the Wick/coupling normalization after
    # pulling out (alpha/pi)^2, as independently checked by the UV residue.
    G5=sp.cancel((120*x*I5-1440*sp.I*x**2*I5k)/(16*Delta**2))
    G4=sp.cancel((
        120*z*I4
        -2880*sp.I*x*z*I4k
        -2880*sp.I*y*z*I4kl
        -1440*sp.I*z**2*I4l
    )/(16*Delta**2))
    return CornerGaussianBareTemplates(G4,G5,red4,red5,(den4k,den4kl,den4l),den5)


def corner_bare_parameter_kernel(diagram,x=None,y=None,z=None,u=None,v=None,rho=None):
    """Substitute the five-simplex quadratic family into generated G4/G5."""
