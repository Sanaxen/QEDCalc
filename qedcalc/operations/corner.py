@dataclass(frozen=True)
class CornerOuterProjectorStreams:
    """Scalar polynomial streams obtained from the finite inner vertex.

    The right-hand corner insertion is projected first.  The mirror graph is
    treated separately by symmetry at assembly time.  Keeping the three pieces
    separate prevents SymPy from constructing a large matrix-valued expression:

      * ``log_base`` / ``log_transverse`` multiply gamma_rho log(Lp/L0),
      * ``lp_base`` / ``lp_transverse`` multiply -C_rho(k)/(2 Lp),
      * ``l0_base`` / ``l0_transverse`` multiply +C_rho(0)/(2 L0).

    ``base`` is the numerator contribution to 2 i M_2^(1)-M_0^(0), while
    ``transverse`` is M_2^(0), needed by the q-derivative of the first outer
    electron denominator.
    """
    k: tuple
    u: sp.Expr
    v: sp.Expr
    rho: sp.Expr
    log_base: sp.Expr
    log_transverse: sp.Expr
    lp_base: sp.Expr
    lp_transverse: sp.Expr
    l0_base: sp.Expr
    l0_transverse: sp.Expr
    term_counts: tuple


@lru_cache(maxsize=1)
def corner_outer_projector_streams() -> CornerOuterProjectorStreams:
    """Project the generated finite inner vertex before outer integration.

    No historical K_nu or I_K/I_z formula is used.  This is the direct bridge
    from the v0.59 raw inner finite remainder to scalar outer-loop polynomials.
    """
    inner=corner_raw_inner_vertex_finite_bridge()
    gu,gl=_corner_explicit_gamma_data(); ident=sp.eye(4)
    k=inner.k; u=inner.u; v=inner.v; rho=inner.rho
    p=(sp.Integer(1),0,0,0)

    def slash(vec):
        return gu[0]*vec[0]-gu[1]*vec[1]-gu[2]*vec[2]-gu[3]*vec[3]

    R=ident+slash(tuple(p[i]-k[i] for i in range(4)))
    qslash=-gu[1]
    bra0=sp.Matrix([[1,0,0,0]])
    braq=sp.Matrix([[0,0,0,-sp.Rational(1,2)]])
    ket=sp.Matrix([1,0,0,0])

    def project(V):
        def chain(mu,q_numerator=False):
            M=sp.zeros(4)
            left=qslash if q_numerator else R
            for rr in range(4):
                M += gu[rr]*left*gl[mu]*R*V[rr]
            return M
        n00=chain(0)
        n20=chain(2)
        n2q=chain(2,True)
        m00=sp.expand((bra0*n00*ket)[0])
        m20=sp.expand((bra0*n20*ket)[0])
        m21=sp.expand((braq*n20*ket)[0]+(bra0*n2q*ket)[0])
        return sp.expand(2*sp.I*m21-m00),m20

    log_base,log_t=project(gl)
    lp_base,lp_t=project(inner.constant_matrices)
    l0_base,l0_t=project(inner.constant_onshell_matrices)
    counts=(
        ('log',len(sp.Poly(log_base,*k).terms()),len(sp.Poly(log_t,*k).terms())),
        ('lambda_prime',len(sp.Poly(lp_base,*k).terms()),len(sp.Poly(lp_t,*k).terms())),
        ('lambda0',len(sp.Poly(l0_base,*k).terms()),len(sp.Poly(l0_t,*k).terms())),
    )
    return CornerOuterProjectorStreams(
        tuple(k),u,v,rho,log_base,log_t,lp_base,lp_t,l0_base,l0_t,counts
    )


