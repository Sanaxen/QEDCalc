@dataclass(frozen=True)
class CornerRawInnerVertexFiniteBridge:
    """Raw inner one-loop vertex after parameter shift and symmetric integration.

    The construction is performed in the rest-frame/Breit-projector convention
    used by the corner raw projector.  The inner Feynman variables are
    ``x=u*v`` and ``y=u*(1-v)``.  After shifting the inner loop momentum ``r``
    the numerator has the exact form

        r^2 gamma_nu + C_nu(k;u,v).

    The dimensionally-regulated radial integral therefore has a UV pole only
    in the gamma_nu channel.  Taking the complete on-shell difference at
    ``k=0`` gives a finite matrix remainder.  Its overall sign is fixed so the
    logarithmic term is +gamma_nu*log(Lambda_prime/Lambda0), matching the
    physical sector convention used by the corner downstream calculation.
    """
    u: sp.Expr
    v: sp.Expr
    rho: sp.Expr
    k: tuple
    lambda0_sq: sp.Expr
    lambda_prime_sq: sp.Expr
    constant_matrices: tuple
    constant_onshell_matrices: tuple
    radial_gamma_residuals: tuple
    finite_remainder_matrices: tuple


def _corner_sym_reduce_inner_matrix_entry(expr, rvars, r2):
    """Drop odd inner-loop terms and reduce rank two in Minkowski signature."""
    metric=(1,-1,-1,-1)
    poly=sp.Poly(sp.expand(expr),*rvars,domain='EX')
    out=sp.Integer(0)
    for powers,coef in poly.terms():
        degree=sum(powers)
        if degree % 2:
            continue
        if degree == 0:
            out += coef
            continue
        if degree == 2:
            inds=[]
            for j,n in enumerate(powers):
                inds.extend([j]*n)
            if len(inds)==2 and inds[0]==inds[1]:
                out += coef*sp.Rational(1,4)*metric[inds[0]]*r2
            continue
        raise ValueError(f"Inner-vertex symmetric reduction encountered rank {degree}; expected <=2.")
    return sp.expand(out)


@lru_cache(maxsize=1)
def corner_raw_inner_vertex_finite_bridge() -> CornerRawInnerVertexFiniteBridge:
    """Generate the on-shell-subtracted inner vertex directly from the raw chain.

    No historical K_nu numerator is supplied.  The function builds

        gamma^alpha [1 + /(p-k-r_old)] gamma_nu
        [1 + /(p-r_old)] gamma_alpha,

    inserts ``r_old = r + u*(p-v*k)``, performs symmetric inner-loop reduction,
    and analytically takes the finite D=4-2*epsilon on-shell difference.
    """
    gu,gl=_corner_explicit_gamma_data(); ident=sp.eye(4)
    u,v,rho=sp.symbols('u v rho', positive=True)
    k=sp.symbols('ik0:4', real=True)
    r=sp.symbols('ir0:4', real=True)
    r2=sp.Symbol('ir2')
    p=(sp.Integer(1),0,0,0)

    def slash(vec):
        return gu[0]*vec[0]-gu[1]*vec[1]-gu[2]*vec[2]-gu[3]*vec[3]

    # x=u*v, y=u*(1-v): inner-loop shift r_old=r+u*(p-v*k).
    shift=tuple(sp.expand(u*(p[i]-v*k[i])) for i in range(4))
    left=tuple(sp.expand(p[i]-k[i]-shift[i]-r[i]) for i in range(4))
    right=tuple(sp.expand(p[i]-shift[i]-r[i]) for i in range(4))
    R1=ident+slash(left)
    R2=ident+slash(right)

    constants=[]; constants0=[]; residuals=[]
    for nu in range(4):
        M=sp.zeros(4)
        for alpha in range(4):
            M += gu[alpha]*R1*gl[nu]*R2*gl[alpha]
        reduced=M.applyfunc(lambda e: _corner_sym_reduce_inner_matrix_entry(e,r,r2))
        radial=reduced.applyfunc(lambda e: sp.expand(e).coeff(r2))
        const=reduced.applyfunc(lambda e: sp.expand(e).subs(r2,0))
        constants.append(const)
        constants0.append(const.subs({kk:0 for kk in k}))
        residuals.append(radial-gl[nu])

    k2=sp.expand(k[0]**2-k[1]**2-k[2]**2-k[3]**2)
    pk=k[0]
    Dk=sp.expand(k2-2*pk)
    L0=sp.expand(u**2+rho**2*(1-u))
    Lp=sp.expand(L0+u**2*v*(1-v)*k2+u*v*(1-u)*Dk)

    # D-dimensional radial finite difference.  With the sign convention chosen
    # to match the physical z-sector, the finite remainder is
    #   gamma log(Lp/L0) - C(k)/(2 Lp) + C(0)/(2 L0).
    finite=[]
    for nu in range(4):
        finite.append(
            gl[nu]*sp.log(Lp/L0)
            - constants[nu]/(2*Lp)
            + constants0[nu]/(2*L0)
        )

    return CornerRawInnerVertexFiniteBridge(
        u=u,v=v,rho=rho,k=tuple(k),lambda0_sq=L0,lambda_prime_sq=Lp,
        constant_matrices=tuple(constants),constant_onshell_matrices=tuple(constants0),
        radial_gamma_residuals=tuple(residuals),finite_remainder_matrices=tuple(finite),
    )


def corner_raw_inner_vertex_radial_residuals():
    """Return 4x4 zero matrices iff the raw r^2 coefficient is gamma_nu."""
