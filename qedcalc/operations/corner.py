def corner_uv_residue_sample(diagram,X,Y,Z,rho):
    """Exact-rational UV residue of the generated bare kernel in a UV chart.

    This helper intentionally substitutes a concrete exact point before taking
    the tau->0 coefficient.  It is used as a fast regression/audit of the full
    symbolic streaming bridge rather than as a numerical approximation.
    """
    X=sp.sympify(X); Y=sp.sympify(Y); Z=sp.sympify(Z); rho=sp.sympify(rho)
    tau=sp.Symbol('tau', positive=True)
    if str(diagram)=='5':
        xx=(1-tau)*X; uu=(1-tau)*(1-X)
        yy=tau*Y; zz=tau*Z; vv=tau*(1-Y-Z)
    elif str(diagram)=='4':
        zz=(1-tau)*X; vv=(1-tau)*(1-X)
        yy=tau*Y; xx=tau*Z; uu=tau*(1-Y-Z)
    else:
        raise ValueError("corner diagram must be 4 or 5")

    # Substitute into the compact template first; this is far faster than
    # expanding the full five-variable rational function and then charting it.
    a=xx+yy+uu; b=yy+zz+vv; c=yy; r=xx+yy; s=yy+zz
    Delta=sp.expand(a*b-c**2)
    W=sp.expand(b*r**2-2*c*r*s+a*s**2)
    Phi=sp.cancel(W/Delta+rho**2*(uu+vv))
    template=corner_gaussian_bare_templates().G5 if str(diagram)=='5' else corner_gaussian_bare_templates().G4
    by_name={'a':a,'b':b,'c':c,'r':r,'s':s,'Delta':Delta,'Phi':Phi,'x':xx,'y':yy,'z':zz}
    expr=template.subs({sym:by_name[sym.name] for sym in template.free_symbols if sym.name in by_name})
    weighted=sp.cancel(tau**3*(1-tau)*expr)
    return sp.simplify(sp.limit(weighted,tau,0))


def corner_local_uv_residue_sample(diagram,X,Y,Z,rho):
    """Exact-rational UV residue of the corresponding local subtraction term."""
    X=sp.sympify(X); Y=sp.sympify(Y); Z=sp.sympify(Z); rho=sp.sympify(rho)
    tau=sp.Symbol('tau', positive=True)
    if str(diagram)=='5':
        xx=(1-tau)*X; uu=(1-tau)*(1-X)
        yy=tau*Y; zz=tau*Z; vv=tau*(1-Y-Z)
    elif str(diagram)=='4':
        zz=(1-tau)*X; vv=(1-tau)*(1-X)
        yy=tau*Y; xx=tau*Z; uu=tau*(1-Y-Z)
    else:
        raise ValueError("corner diagram must be 4 or 5")
    uv=corner_local_uv_subtractions(xx,yy,zz,uu,vv,rho)
    expr=uv.GUV5 if str(diagram)=='5' else uv.GUV4
    return sp.simplify(sp.limit(sp.cancel(tau**3*(1-tau)*expr),tau,0))


def corner_uv_subtracted_residue_sample(diagram,X,Y,Z,rho):
    return sp.simplify(
        corner_uv_residue_sample(diagram,X,Y,Z,rho)
        - corner_local_uv_residue_sample(diagram,X,Y,Z,rho)
    )

