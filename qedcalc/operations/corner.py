@lru_cache(maxsize=1)
def corner_log_gaussian_bridge() -> CornerLogGaussianBridge:
    """Gaussian-reduce log(Lambda'/Lambda0) after restoring its z integral.

    log(Lp/L0)=(Lp-L0) int_0^1 dz/Lz and
      Lp-L0 = u^2 v(1-v) K + u v(1-u) D.
    Hence two lower-denominator families appear naturally:
      * K cancellation: 1/(D^2 Lz),
      * D cancellation: 1/(K D Lz).
    """
    q=corner_outer_common_quotients(); s=corner_outer_projector_streams()
    u,v,rho=s.u,s.v,s.rho; k=s.k
    z=sp.Symbol('z_inner', nonnegative=True)
    AK=u**2*v*(1-v); AD=u*v*(1-u)

    # Family A: 1/(D^2 Lz), combine D^2 and Lz with a_l in [0,1], a_d=1-a_l.
    al=sp.Symbol('a_l', nonnegative=True); ad=sp.expand(1-al)
    dA=corner_outer_stream_denominators(u,v,rho,ad,al,z)
    # Since photon K is cancelled, H must be rebuilt without its Feynman weight.
    # Combined D/Lz quadratic coefficients:
    A1=sp.expand(ad + al*z*u*v*(1-u*v))
    B1=sp.expand(ad + al*z*u*v*(1-u))
    const1=sp.expand(al*(u**2+rho**2*(1-u)))
    C1=sp.expand(const1 + B1**2/A1)
    # 1/(D^2 Lz)=2 ad/M^3.
    pc_raw=2*ad*AK*_corner_one_loop_gaussian_stream(q.log_quotient,3,k,B1/A1,A1,C1)
    pc,pc_poles=_corner_strip_zero_poles(pc_raw)

    # Family B: 1/(K D Lz), three simple denominators on a 2-simplex.
    ap,ad2=sp.symbols('a_p a_d', nonnegative=True); al2=sp.expand(1-ap-ad2)
    A2=sp.expand(ap+ad2+al2*z*u*v*(1-u*v))
    B2=sp.expand(ad2+al2*z*u*v*(1-u))
    const2=sp.expand(ap*rho**2+al2*(u**2+rho**2*(1-u)))
    C2=sp.expand(const2+B2**2/A2)
    # 1/(K D Lz)=2/M^3.
    ec_raw=2*AD*_corner_one_loop_gaussian_stream(q.log_quotient,3,k,B2/A2,A2,C2)
    ec,ec_poles=_corner_strip_zero_poles(ec_raw)
    return CornerLogGaussianBridge(pc,ec,pc_poles,ec_poles,(u,v,rho,z,al,ap,ad2))


