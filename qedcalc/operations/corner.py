@dataclass(frozen=True)
class RawCornerStructure:
    diagram: str
    electron_momenta: tuple
    electron_labels: tuple
    photon_labels: tuple
    q0_denominator_powers: tuple
    inner_vertex_side: str
    inner_vertex_propagators: tuple
    inner_external_electrons: tuple
    scalarized_integrand: object


def _corner_electron_label(momentum):
    c=_linear_vector_coeffs(momentum)
    key=tuple(sorted(c.items()))
    table={
        tuple(sorted({"p'":1,"k":-1}.items())):"p'-k",
        tuple(sorted({"p":1,"k":-1}.items())):"p-k",
        tuple(sorted({"p'":1,"k":-1,"l":-1}.items())):"p'-k-l",
        tuple(sorted({"p":1,"k":-1,"l":-1}.items())):"p-k-l",
        tuple(sorted({"p'":1,"l":-1}.items())):"p'-l",
        tuple(sorted({"p":1,"l":-1}.items())):"p-l",
    }
    if key not in table:
        raise ValueError(f"Unrecognized corner electron momentum: {c}")
    return table[key]


def analyze_raw_corner(diagram: LoopIntegralExpression) -> RawCornerStructure:
    """Recognize either of the two Feynman-gauge corner (IIc) bare diagrams."""
    loops=tuple(v.name for v in diagram.loops)
    if loops != ("k","l"):
        raise ValueError(f"Corner raw bridge expects loops (k,l), found {loops}.")
    factors=diagram.integrand.factors if isinstance(diagram.integrand,NCProduct) else (diagram.integrand,)
    fermions=[f for f in factors if isinstance(f,Fraction) and any(isinstance(n,Slash) for n in f.denominator.walk())]
    if len(fermions)!=4:
        raise ValueError(f"Expected four corner electron propagators, found {len(fermions)}.")
    momenta=tuple(_fermion_momentum_from_fraction(f) for f in fermions)
    labels=tuple(_corner_electron_label(p) for p in momenta)
    pattern5=("p'-k","p-k","p-k-l","p-l")
    pattern4=("p'-k","p'-k-l","p'-l","p-l")
    if labels==pattern5:
        name="5"; side="right"; inner=("p-k-l","p-l"); ext=("p-k","p")
        q0=(2,1,1,1,1) # Dk,Dkl,Dl,K,L
    elif labels==pattern4:
        name="4"; side="left"; inner=("p'-k-l","p'-l"); ext=("p'-k","p'")
        q0=(1,1,2,1,1)
    else:
        raise ValueError(f"Unexpected corner electron ordering: {labels}")
    scalar_fracs=[f for f in factors if isinstance(f,Fraction) and isinstance(f.numerator,Symbol) and f.numerator.name=="1" and not any(isinstance(n,Slash) for n in f.denominator.walk())]
    photon_names=[_fraction_square_loop_name(f) for f in scalar_fracs]
    photon_names=[n for n in photon_names if n in ("k","l")]
    if sorted(photon_names)!=["k","l"]:
        raise ValueError(f"Expected corner photon denominators k,l, found {photon_names}")
    recognized=recognize_propagators(diagram.integrand)
    scalarized=scalarize_fermion_propagators(recognized)
    frac=separate_numerator_denominator(scalarized)
    return RawCornerStructure(
        diagram=name,
        electron_momenta=momenta,
        electron_labels=labels,
        photon_labels=tuple("K" if n=="k" else "L" for n in photon_names),
        q0_denominator_powers=q0,
        inner_vertex_side=side,
        inner_vertex_propagators=inner,
        inner_external_electrons=ext,
        scalarized_integrand=frac,
    )


