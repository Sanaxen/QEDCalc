def _corner_poly_divisible(expr, divisor, variables):
    q,r=sp.div(sp.Poly(sp.expand(expr),*variables,domain='EX'),
               sp.Poly(sp.expand(divisor),*variables,domain='EX'))
    return bool(r.is_zero),sp.expand(q.as_expr()),sp.expand(r.as_expr())


@lru_cache(maxsize=1)
def corner_historical_K_sector_decomposition_audit() -> CornerHistoricalKSectorDecompositionAudit:
    h=corner_historical_K_projector_audit()
    gu,gl=_corner_explicit_gamma_data(); ident=sp.eye(4)
    k=h.k; D=h.D; k2=h.k2
    p=(sp.Integer(1),0,0,0)

    def slash(vec):
        return gu[0]*vec[0]-gu[1]*vec[1]-gu[2]*vec[2]-gu[3]*vec[3]

    pk=tuple(sp.expand(p[j]-k[j]) for j in range(4))
    R=ident+slash(pk); qslash=-gu[1]
    bra0=sp.Matrix([[1,0,0,0]])
    braq=sp.Matrix([[0,0,0,-sp.Rational(1,2)]])
    ket=sp.Matrix([1,0,0,0])

    def project(V):
        def chain(mu,q_numerator=False):
            out=sp.zeros(4); left=qslash if q_numerator else R
            for nu in range(4):
                out += gu[nu]*left*gl[mu]*R*V[nu]
            return out
        n00=chain(0); n20=chain(2); n2q=chain(2,True)
        m00=sp.expand((bra0*n00*ket)[0])
        m20=sp.expand((bra0*n20*ket)[0])
        m21=sp.expand((braq*n20*ket)[0]+(bra0*n2q*ket)[0])
        base=sp.expand(2*sp.I*m21-m00)
        return base,m20

    pb,pt=project(h.K_pres_matrices)
    db,dt=project(h.K_D_matrices)
    kb,kt=project(h.K_k2_matrices)
    fullb=sp.expand(pb+db+kb)
    fullt=sp.expand(pt+dt+kt)

    pc=sp.expand(D*pb+4*sp.I*k[1]*pt)
    dc=sp.expand(D*db+4*sp.I*k[1]*dt)
    kc=sp.expand(D*kb+4*sp.I*k[1]*kt)
    fullc=sp.expand(pc+dc+kc)

    db_div,_,_=_corner_poly_divisible(db,D,k)
    dt_div,_,_=_corner_poly_divisible(dt,D,k)
    kb_div,_,_=_corner_poly_divisible(kb,k2,k)
    kt_div,_,_=_corner_poly_divisible(kt,k2,k)

    return CornerHistoricalKSectorDecompositionAudit(
        D=D,k2=k2,k=tuple(k),
        pres_base=pb,pres_transverse=pt,
        D_base=db,D_transverse=dt,
        k2_base=kb,k2_transverse=kt,
        full_base_residual=sp.expand(fullb-h.base),
        full_transverse_residual=sp.expand(fullt-h.transverse),
        pres_common=pc,D_common=dc,k2_common=kc,
        full_common_residual=sp.expand(fullc-h.common_numerator),
        D_base_divisible=db_div,D_transverse_divisible=dt_div,
        k2_base_divisible=kb_div,k2_transverse_divisible=kt_div,
    )


