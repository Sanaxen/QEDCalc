def corner_cancellation_first_rational_qmc(rho_value, *, power=11, seed=1):
    """Diagnostic QMC of the convention-resolved cancellation-first rational route."""
    try:
        import numpy as np
        from scipy.stats import qmc
    except Exception as exc:  # pragma: no cover
        raise RuntimeError('cancellation-first QMC requires NumPy and SciPy') from exc
    rho=float(rho_value); funcs=_corner_cancellation_first_numpy_functions()
    L=np.log((1.0+rho)/rho); eps=np.finfo(float).eps
    def umap(t):
        e=np.exp(L*t); return rho*(e-1.0),rho*L*e
    def simplex(u,x,y):
        r=u*x/(1-x); s=u*y/(1-y); den=1+r+s
        ad=r/den; ap=s/den; al=1/den
        J=u*u/((1-x)**2*(1-y)**2*den**3)
        return ad,ap,al,J
    def line(u,x):
        r=u*x/(1-x); den=1+r; ad=r/den; al=1/den
        J=u/((1-x)**2*den**2); return ad,al,J
    order=('preserving','D_cancel','k2_cancel','kappa_Lp','kappa_L0'); out={}
    for j,name in enumerate(order):
        d=4 if name in ('preserving','D_cancel','kappa_Lp') else (3 if name=='k2_cancel' else 2)
        pts=qmc.Sobol(d,scramble=True,seed=int(seed)+211*j).random_base2(int(power))
        pts=np.clip(pts,eps,1-eps); u,du=umap(pts[:,0])
        if name in ('preserving','D_cancel','kappa_Lp'):
            v=pts[:,1]; ad,ap,al,J=simplex(u,pts[:,2],pts[:,3])
            val=funcs[name](u,v,rho,ad,al); w=u*du*J
        elif name=='k2_cancel':
            v=pts[:,1]; ad,al,J=line(u,pts[:,2])
            val=funcs[name](u,v,rho,ad); w=u*du*J
        else:
            ad,al,J=line(u,pts[:,1]); val=funcs[name](u,rho,ad); w=u*du*J
        arr=np.asarray(val,dtype=float)*w; good=arr[np.isfinite(arr)]
        mean=float(np.mean(good)); err=float(np.std(good,ddof=1)/np.sqrt(good.size))
        out[name]={'mean_before_quarter':mean,'stderr_before_quarter':err,'samples':int(good.size)}
    total=sum(out[n]['mean_before_quarter'] for n in order); err=sum(out[n]['stderr_before_quarter']**2 for n in order)**0.5
    import math
    out['assembled']={'rho':rho,'rational_physical':total/4,'rational_minus_log':total/4-math.log(1/rho),'stderr':err/4,'role':'cancellation-first diagnostic; no archived value used as input'}
    return out

