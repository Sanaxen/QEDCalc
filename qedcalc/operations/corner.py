def corner_q0_parametric_family(x=None,y=None,z=None,u=None,v=None,rho=None,t=None):
    """Common q=0 five-denominator family for the two corner diagrams.

    The squared electron denominator is split until after q differentiation.
    Returned q-derivative coefficients multiply ``2 q.(c_k k+c_l l)``.
    """
    x=sp.Symbol('x') if x is None else sp.sympify(x)
    y=sp.Symbol('y') if y is None else sp.sympify(y)
    z=sp.Symbol('z') if z is None else sp.sympify(z)
    u=sp.Symbol('u') if u is None else sp.sympify(u)
    v=sp.Symbol('v') if v is None else sp.sympify(v)
    rho=sp.Symbol('rho') if rho is None else sp.sympify(rho)
    t=sp.Symbol('t') if t is None else sp.sympify(t)
    aa=sp.expand(x+y+u); bb=sp.expand(y+z+v); cc=y
    rr=sp.expand(x+y); ss=sp.expand(y+z)
    Delta=sp.expand(aa*bb-cc**2)
    W=sp.expand(bb*rr**2-2*cc*rr*ss+aa*ss**2)
    Omega=sp.expand(W+rho**2*(u+v)*Delta)
    return CornerParametricFamily(
        aa,bb,cc,rr,ss,Delta,W,Omega,
        sp.expand(120*z),sp.expand(120*x),
        sp.expand(x+y),sp.expand(y+z*t),
        sp.expand(x*t),sp.Integer(0),
    )


def corner_vertex_B_integrand(u=None,k2=None,m2=None,lambda2=None):
    """Integrand of the on-shell vertex subtraction coefficient B.

    The overall 1/(i*pi^2) and du d^4k measures are not included.
    """
    u=sp.Symbol('u') if u is None else sp.sympify(u)
    k2=sp.Symbol('k2') if k2 is None else sp.sympify(k2)
    m2=sp.Symbol('m2') if m2 is None else sp.sympify(m2)
    lambda2=sp.Symbol('lambda2') if lambda2 is None else sp.sympify(lambda2)
    Lambda0=sp.expand(m2*u**2+lambda2*(1-u))
    return sp.factor(u*(k2-4*m2*(1-u-sp.Rational(1,2)*u**2))/(k2+Lambda0)**3)


def _corner_explicit_gamma_data():
    I=sp.I; zero=sp.zeros(2)
    sx=sp.Matrix([[0,1],[1,0]]); sy=sp.Matrix([[0,-I],[I,0]]); sz=sp.Matrix([[1,0],[0,-1]])
    g0=sp.diag(1,1,-1,-1)
    def gi(sig): return sp.Matrix.vstack(sp.Matrix.hstack(zero,sig),sp.Matrix.hstack(-sig,zero))
    gu=(g0,gi(sx),gi(sy),gi(sz)); metric=(1,-1,-1,-1)
    gl=tuple(metric[i]*gu[i] for i in range(4))
    return gu,gl


@dataclass(frozen=True)
class CornerProjectorPolynomialAudit:
    diagram4_base: sp.Expr
    diagram5_base: sp.Expr
    diagram4_transverse_zero: sp.Expr
    diagram5_transverse_zero: sp.Expr
    term_counts: tuple


@lru_cache(maxsize=1)
def corner_raw_projector_polynomials() -> CornerProjectorPolynomialAudit:
    """Generate the q-linear magnetic projector polynomials of corner diagrams 4/5."""
    gu,gl=_corner_explicit_gamma_data(); ident=sp.eye(4)
    k=sp.symbols('ck0:4'); l=sp.symbols('cl0:4')
    def slash(v): return gu[0]*v[0]-gu[1]*v[1]-gu[2]*v[2]-gu[3]*v[3]
    p=(sp.Integer(1),0,0,0); qslash=-gu[1]
    Rk=ident+slash(tuple(p[i]-k[i] for i in range(4)))
    Rl=ident+slash(tuple(p[i]-l[i] for i in range(4)))
    Rkl=ident+slash(tuple(p[i]-k[i]-l[i] for i in range(4)))

    def chain(diagram,mu):
        n0=sp.zeros(4); nq=sp.zeros(4)
        for rho in range(4):
            for alpha in range(4):
                if diagram=='5':
                    n0 += gu[rho]*Rk*gl[mu]*Rk*gu[alpha]*Rkl*gl[rho]*Rl*gl[alpha]
                    nq += gu[rho]*qslash*gl[mu]*Rk*gu[alpha]*Rkl*gl[rho]*Rl*gl[alpha]
                else:
                    n0 += gu[rho]*Rk*gu[alpha]*Rkl*gl[rho]*Rl*gl[mu]*Rl*gl[alpha]
                    nq += gu[rho]*qslash*gu[alpha]*Rkl*gl[rho]*Rl*gl[mu]*Rl*gl[alpha]
                    nq += gu[rho]*Rk*gu[alpha]*qslash*gl[rho]*Rl*gl[mu]*Rl*gl[alpha]
                    nq += gu[rho]*Rk*gu[alpha]*Rkl*gl[rho]*qslash*gl[mu]*Rl*gl[alpha]
        return n0,nq

    bra0=sp.Matrix([[1,0,0,0]]); braq=sp.Matrix([[0,0,0,-sp.Rational(1,2)]]); ket=sp.Matrix([1,0,0,0])
    bases={}; m20={}; counts=[]
    variables=tuple(k)+tuple(l)
    for diagram in ('4','5'):
        n00,_=chain(diagram,0); n20,n2q=chain(diagram,2)
        m00=sp.expand((bra0*n00*ket)[0])
        m20[diagram]=sp.expand((bra0*n20*ket)[0])
        m21=sp.expand((braq*n20*ket)[0]+(bra0*n2q*ket)[0])
        bases[diagram]=sp.expand(2*sp.I*m21-m00)
        counts.append((diagram,len(sp.Poly(bases[diagram],*variables).terms()),len(sp.Poly(m20[diagram],*variables).terms())))
    return CornerProjectorPolynomialAudit(bases['4'],bases['5'],m20['4'],m20['5'],tuple(counts))

