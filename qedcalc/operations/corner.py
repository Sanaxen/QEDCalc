    Kker=sp.cancel(2*ad*Gk.subs({S:Bs/H,A:H,C:Q/H}))

    # kappa Lp: K D^2 Lp, weight 6 a_d.
    H,Bs,Q=general_sub(1-ad-al,ad,al)
    KLp=sp.cancel(6*ad*Gkap.subs({S:Bs/H,A:H,C:Q/H}))

    # kappa L0: K D^2 times 1/L0, powers (1,2), weight 2 a_d.
    Q0=sp.expand(ad**2+(1-ad)*rho**2)
    KL0=sp.cancel(2*ad/L0*Gl0.subs({S:ad,A:sp.Integer(1),C:Q0}))

    return CornerCancellationFirstRationalKernels(
        Pker,Dker,Kker,KLp,KL0,
        (u,v,rho,ad,al),(u,v,rho,ad,al),(u,v,rho,ad),
        (u,v,rho,ad,al),(u,rho,ad),
    )


