@lru_cache(maxsize=1)
def corner_B_finite_normalization_audit() -> CornerBFiniteNormalizationAudit:
    """Derive the finite on-shell B normalization from the radial masters.

    For D=4-2 epsilon, the normalized k^2 master contributes

        (1-epsilon/2) Gamma(epsilon) L^{-epsilon}
          = pole - log(L) - 1/2 + O(epsilon),

    while the scalar master contributes -2 f(u)/L.  This gives the finite
    u-integrand below without importing the historical final constant.

    The small-rho constant is then derived by polynomial division of
    u*f(u)/L.  The logarithmic piece has coefficient -1 and the quotient
    contributes -5/4.  Together with -int u log(u^2) du = 1/2 and the
    explicit -1/2 term integrated with u du, one obtains 11/4.
    """
    u,rho=sp.symbols('u rho', positive=True)
    L=sp.expand(u**2+rho**2*(1-u))
    f=sp.expand(1-u-u**2/sp.Integer(2))
    finite=sp.factor(u*(-sp.log(L)-sp.Rational(1,2)-2*f/L))

    N=sp.expand(u*f)
    q,rem=sp.div(sp.Poly(N,u,domain='EX'),sp.Poly(L,u,domain='EX'))
    qq=sp.expand(q.as_expr()); rr=sp.expand(rem.as_expr())
    residual=sp.expand(N-qq*L-rr)

    # rho->0 constants derived from the exact quotient/remainder structure.
    # -int_0^1 u log(u^2) du = 1/2.
    hard_log=sp.integrate(-u*sp.log(u**2),(u,0,1))
    # For J=int u*f/L, the quotient tends -u/2-1, whose integral is -5/4;
    # the remainder supplies the universal -log(rho) and no additional O(1)
    # constant because rho^2*int du/L -> 0.
    rational_const=sp.integrate(-u/sp.Integer(2)-1,(u,0,1))
    explicit_const=sp.integrate(-u/sp.Integer(2),(u,0,1))
    Bconst=sp.simplify(hard_log+explicit_const-2*rational_const)
    schwinger=sp.Rational(1,2)
    ctconst=sp.simplify(-Bconst*schwinger)

    return CornerBFiniteNormalizationAudit(
        u,rho,L,f,finite,qq,rr,residual,hard_log,rational_const,
        Bconst,schwinger,ctconst
    )


