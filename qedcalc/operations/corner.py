@dataclass(frozen=True)
class CornerOuterQuadraticBridge:
    """Outer-loop quadratic form generated from the renormalized inner denominator.

    This is the rho=0 bulk denominator layer.  It starts from

        Lambda'^2 = u^2 + u*v*(1-u) D(k) + u^2*v*(1-v) k^2,
        D(k)       = k^2 - 2 p.k,

    and combines the outer photon/electron/inner denominators with simplex
    weights ``a_p,a_d,a_l``.  No downstream Q/H polynomial is supplied as an
    input; H, shift coefficient B, and Q are generated from those ingredients.
    """
    a_p: sp.Expr
    lambda_prime_k2_coefficient: sp.Expr
    lambda_prime_pk_coefficient: sp.Expr
    H: sp.Expr
    shift_B: sp.Expr
    Q: sp.Expr
    H_z: sp.Expr
    shift_B_z: sp.Expr
    Q_z: sp.Expr


def corner_lambda_prime_bulk_coefficients(u=None, v=None):
    """Return coefficients of Lambda'^2 at rho=0 in the (k^2,p.k,1) basis.

    Lambda'^2 = u^2 + A k^2 - 2 B p.k,
    where A=u*v*(1-u*v) and B=u*v*(1-u).
    """
    u=sp.Symbol('u', positive=True) if u is None else sp.sympify(u)
    v=sp.Symbol('v', real=True) if v is None else sp.sympify(v)
    A=sp.factor(u**2*v*(1-v)+u*v*(1-u))
    B=sp.factor(u*v*(1-u))
    return {
        'k2': A,
        'pk': B,
        'constant': sp.expand(u**2),
    }


def corner_outer_quadratic_bridge(u=None,v=None,a_d=None,a_l=None,z_inner=None):
    """Generate the bulk and z-sector outer square-completion polynomials.

    ``a_p=1-a_d-a_l`` weights the outer photon denominator, ``a_d`` the
    outer electron denominator D(k), and ``a_l`` the renormalized inner
    denominator.  For the z sector the inner denominator is the interpolation
    Lambda0^2 + z (Lambda'^2-Lambda0^2).
    """
    u=sp.Symbol('u', positive=True) if u is None else sp.sympify(u)
    v=sp.Symbol('v', real=True) if v is None else sp.sympify(v)
    ad=sp.Symbol('a_d', nonnegative=True) if a_d is None else sp.sympify(a_d)
    al=sp.Symbol('a_l', nonnegative=True) if a_l is None else sp.sympify(a_l)
    zz=sp.Symbol('z_inner', real=True) if z_inner is None else sp.sympify(z_inner)
    ap=sp.expand(1-ad-al)
    lp=corner_lambda_prime_bulk_coefficients(u,v)

    # Combined denominator coefficients before the shift:
    #   H k^2 - 2 B p.k + a_l u^2.
    H=sp.factor(ap+ad+al*lp['k2'])
    B=sp.factor(ad+al*lp['pk'])
    Q=sp.expand(B**2+al*u**2*H)

    # z-sector interpolation only scales Lambda'^2-Lambda0^2.
    Hz=sp.factor(ap+ad+al*zz*lp['k2'])
    Bz=sp.factor(ad+al*zz*lp['pk'])
    Qz=sp.expand(Bz**2+al*u**2*Hz)
    return CornerOuterQuadraticBridge(ap,lp['k2'],lp['pk'],H,B,Q,Hz,Bz,Qz)


def corner_outer_quadratic_checkpoint_residuals(u=None,v=None,a_d=None,a_l=None,z_inner=None):
    """Compare generated H,Q,H_z,Q_z with independently archived downstream forms."""
    u=sp.Symbol('u', positive=True) if u is None else sp.sympify(u)
    v=sp.Symbol('v', real=True) if v is None else sp.sympify(v)
    ad=sp.Symbol('a_d', nonnegative=True) if a_d is None else sp.sympify(a_d)
    al=sp.Symbol('a_l', nonnegative=True) if a_l is None else sp.sympify(a_l)
    zz=sp.Symbol('z_inner', real=True) if z_inner is None else sp.sympify(z_inner)
    b=corner_outer_quadratic_bridge(u,v,ad,al,zz)
    H_ref=sp.expand(1-al*(1-u*v+u**2*v**2))
    Q_ref=sp.expand(
        ad**2-2*ad*al*u**2*v+2*ad*al*u*v
        -2*al**2*u**3*v**2+al**2*u**3*v+al**2*u**2*v**2-al**2*u**2+al*u**2
    )
    Hz_ref=sp.expand(1-al*(1-u*v*zz+u**2*v**2*zz))
    Qz_ref=sp.expand((ad-al*u*v*zz*(u-1))**2+al*u**2*Hz_ref)
    return {
        'H': sp.simplify(sp.expand(b.H-H_ref)),
        'Q': sp.simplify(sp.expand(b.Q-Q_ref)),
        'H_z': sp.simplify(sp.expand(b.H_z-Hz_ref)),
        'Q_z': sp.simplify(sp.expand(b.Q_z-Qz_ref)),
        'Q_completed_square': sp.simplify(sp.expand(b.Q-(b.shift_B**2+al*u**2*b.H))),
        'Q_z_completed_square': sp.simplify(sp.expand(b.Q_z-(b.shift_B_z**2+al*u**2*b.H_z))),
    }


def corner_lambda_prime_bulk_expression(u=None,v=None,k2=None,pk=None):
    """Construct Lambda'^2 at rho=0 directly from D(k)=k^2-2 p.k."""
    u=sp.Symbol('u', positive=True) if u is None else sp.sympify(u)
    v=sp.Symbol('v', real=True) if v is None else sp.sympify(v)
    k2=sp.Symbol('k2') if k2 is None else sp.sympify(k2)
    pk=sp.Symbol('pk') if pk is None else sp.sympify(pk)
    D=sp.expand(k2-2*pk)
    return sp.expand(u**2 + u**2*v*(1-v)*k2 + u*v*(1-u)*D)


def corner_outer_combined_bulk_denominator(u=None,v=None,a_d=None,a_l=None,k2=None,pk=None):
    """Combine the photon, electron and generated Lambda' denominators before shift."""
    u=sp.Symbol('u', positive=True) if u is None else sp.sympify(u)
    v=sp.Symbol('v', real=True) if v is None else sp.sympify(v)
    ad=sp.Symbol('a_d', nonnegative=True) if a_d is None else sp.sympify(a_d)
    al=sp.Symbol('a_l', nonnegative=True) if a_l is None else sp.sympify(a_l)
    k2=sp.Symbol('k2') if k2 is None else sp.sympify(k2)
    pk=sp.Symbol('pk') if pk is None else sp.sympify(pk)
    ap=sp.expand(1-ad-al)
    D=sp.expand(k2-2*pk)
    Lp=corner_lambda_prime_bulk_expression(u,v,k2,pk)
    return sp.expand(ap*k2 + ad*D + al*Lp)

