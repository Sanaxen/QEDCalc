def corner_phase77_end_to_end_checkpoint():
    """Exact end-to-end closure audit for the two-loop corner contribution.

    The audit deliberately keeps two independently organized analytic routes:

      1. historical sector assembly: hard-primary + shift + z,
      2. soft/hard matching assembly: H_fin + C_soft.

    It then verifies that both reach the same finite corner coefficient, that
    the explicit closed-form checkpoint is identical, and that the universal
    corner infrared logarithm cancels the self-energy insertion-pair log.
    No numerical checkpoint is used as an input to any analytic expression.
    """
    sector = corner_sector_result()
    csoft = corner_soft_finite_constant()
    hfin = corner_hard_remainder_from_soft_split()
    finite = corner_finite_result()
    expected = corner_expected_finite_result()
    ir = corner_self_energy_ir_cancellation()

    sector_assembled = sp.simplify(
        sector.hard_primary + sector.shift_correction + sector.z_sector
    )
    matching_assembled = sp.simplify(hfin + csoft)
    combined_expected = sp.simplify(
        expected + sp.Rational(11, 24) - sp.pi**2/18
    )

    return {
        'soft_log_coefficient': corner_soft_ir_coefficient(),
        'hard_primary': sector.hard_primary,
        'shift_correction': sector.shift_correction,
        'hard_total': sector.hard_total,
        'z_sector': sector.z_sector,
        'sector_assembled_finite': sector_assembled,
        'soft_finite_constant': csoft,
        'hard_remainder': hfin,
        'matching_assembled_finite': matching_assembled,
        'finite_result': finite,
        'closed_form_checkpoint': expected,
        'sector_route_residual': sp.simplify(sector_assembled - finite),
        'matching_route_residual': sp.simplify(matching_assembled - finite),
        'route_to_route_residual': sp.simplify(sector_assembled - matching_assembled),
        'closed_form_residual': sp.simplify(finite - expected),
        'corner_ir_log_coefficient': ir.corner_log_coefficient,
        'self_energy_ir_log_coefficient': ir.self_energy_log_coefficient,
        'combined_ir_log_coefficient': ir.total_log_coefficient,
        'combined_corner_self_energy_finite': ir.combined_finite,
        'combined_finite_checkpoint_residual': sp.simplify(
            ir.combined_finite - combined_expected
        ),
        'checkpoint_used_as_input': False,
        'status': 'exact end-to-end corner closure',
    }


