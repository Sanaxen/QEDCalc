def corner_finite_rho_qmc(rho_value, *, power=12, seed=1):
    """Evaluate the current generated finite-rho corner representation.

    This is a *diagnostic/regression* evaluator, not an analytic input.  It
    compiles the SymPy-generated kernels and integrates every family with the
    exact Phase-64 measure ownership.  Scrambled Sobol points are used when
    NumPy/SciPy are available.  Neither the Petermann finite value nor archived
    QMC checkpoints are used to construct or modify the integrand.

    Returns a dictionary containing each family mean/error, the assembled
    ``A_C(rho)`` and ``A_C(rho)-log(1/rho)``.  The five families are sampled
    independently; reported family standard errors are therefore combined in
    quadrature for the assembled diagnostic uncertainty.
    """
    try:
        import numpy as np
        from scipy.stats import qmc
    except Exception as exc:  # pragma: no cover - optional runtime path
        raise RuntimeError('corner finite-rho QMC requires NumPy and SciPy') from exc

    rho=float(rho_value)
    if not (0.0 < rho < 1.0):
        raise ValueError('rho_value must satisfy 0 < rho < 1')
    if power < 4:
        raise ValueError('power must be >= 4')

    funcs=_corner_finite_rho_numpy_functions()
    L=np.log((1.0+rho)/rho)
    eps=np.finfo(float).eps

    def umap(t):
        e=np.exp(L*t)
        return rho*(e-1.0), rho*L*e

    def simplex(u,x,y):
        r=u*x/(1.0-x); s=u*y/(1.0-y); den=1.0+r+s
        ad=r/den; ap=s/den; al=1.0/den
        J=u*u/((1.0-x)**2*(1.0-y)**2*den**3)
        return ad,ap,al,J

    def line(u,x):
        r=u*x/(1.0-x); den=1.0+r
        ad=r/den; al=1.0/den
        J=u/((1.0-x)**2*den**2)
        return ad,al,J

    dims=dict(corner_finite_rho_numerical_measure_audit().family_dimensions)
    order=('lp','B_gamma','log_photon_cancel','log_electron_cancel','log_photon_mass_residual')
    out={}
    for j,name in enumerate(order):
        d=dims[name]
        pts=qmc.Sobol(d,scramble=True,seed=int(seed)+101*j).random_base2(int(power))
        pts=np.clip(pts,eps,1.0-eps)
        u,du=umap(pts[:,0])
        if name == 'lp':
            v=pts[:,1]; ad,ap,al,J=simplex(u,pts[:,2],pts[:,3])
            val=funcs[name](u,v,rho,ad,al); weight=u*du*J
        elif name == 'B_gamma':
            ad,al,J=line(u,pts[:,1])
            val=funcs[name](u,rho,ad); weight=u*du*J
        elif name == 'log_photon_cancel':
            v=pts[:,1]; z=pts[:,2]; ad,al,J=line(u,pts[:,3])
            val=funcs[name](u,v,rho,z,al); weight=u*du*J
        else:
            v=pts[:,1]; z=pts[:,2]; ad,ap,al,J=simplex(u,pts[:,3],pts[:,4])
            val=funcs[name](u,v,rho,z,ap,ad); weight=u*du*J
        arr=np.asarray(val,dtype=float)*weight
        finite=np.isfinite(arr)
        if not finite.any():
            raise FloatingPointError(f'no finite samples for corner family {name}')
        good=arr[finite]
        mean=float(np.mean(good))
        stderr=float(np.std(good,ddof=1)/np.sqrt(good.size)) if good.size>1 else 0.0
        out[name]={
            'mean_before_quarter':mean,
            'stderr_before_quarter':stderr,
            'finite_fraction':float(np.mean(finite)),
            'samples':int(good.size),
        }

    total=sum(out[n]['mean_before_quarter'] for n in order)
    err=(sum(out[n]['stderr_before_quarter']**2 for n in order))**0.5
    A=total/4.0; Aerr=err/4.0
    out['assembled']={
        'rho':rho,
        'normalization':0.25,
        'A_C':A,
        'stderr':Aerr,
        'finite_minus_log':A-float(np.log(1.0/rho)),
        'power':int(power),
        'seed':int(seed),
        'role':'generated-kernel diagnostic; no archived checkpoint used as input',
    }
    return out


