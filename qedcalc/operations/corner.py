@dataclass(frozen=True)
class CornerOuterCommonQuotients:
    """Projector streams after numerator/denominator q terms are combined.

    Each stream is first written over a common outer electron denominator D^3.
    Polynomial division then gives

        N_common = D * Q_eff + R_odd,

    where R_odd integrates to zero because every monomial is odd in at least one
    transverse spatial loop component.  This ordering is essential: integrating
    the base and denominator-derivative pieces separately produces spurious
    Gamma(0) terms.
    """
    k: tuple
    D: sp.Expr
    log_quotient: sp.Expr
    log_remainder: sp.Expr
    lp_quotient: sp.Expr
    lp_remainder: sp.Expr
    l0_quotient: sp.Expr
    l0_remainder: sp.Expr
    counts: tuple
    odd_flags: tuple


def _corner_remainder_transverse_odd(expr, k):
    """True iff every monomial is odd in at least one unshifted spatial axis."""
    expr=sp.expand(expr)
    if expr == 0:
        return True
    poly=sp.Poly(expr,*k,domain='EX')
    for powers,_ in poly.terms():
        # k0 is shifted by the square completion; k1,k2,k3 are not.
        if not any(powers[j] % 2 for j in (1,2,3)):
            return False
    return True


@lru_cache(maxsize=1)
def corner_outer_common_quotients() -> CornerOuterCommonQuotients:
    """Combine q-linear denominator pieces before Gaussian reduction."""
    s=corner_outer_projector_streams(); k=s.k
    k2=sp.expand(k[0]**2-k[1]**2-k[2]**2-k[3]**2)
    D=sp.expand(k2-2*k[0])
    rows=[]
    for name,base,trans in (
        ('log',s.log_base,s.log_transverse),
        ('lambda_prime',s.lp_base,s.lp_transverse),
        ('lambda0',s.l0_base,s.l0_transverse),
    ):
        # dD1/dq=-2*k1, hence d(1/D1)/dq=+2*k1/D1^2.
        # The magnetic projector contributes another factor 2*i.
        common=sp.expand(D*base + 4*sp.I*k[1]*trans)
        q,r=sp.div(sp.Poly(common,*k,domain='EX'),sp.Poly(D,*k,domain='EX'))
        qe=sp.expand(q.as_expr()); re=sp.expand(r.as_expr())
        rows.append((name,qe,re,len(q.terms()),len(r.terms()),_corner_remainder_transverse_odd(re,k)))
    d={row[0]:row for row in rows}
    return CornerOuterCommonQuotients(
        k=tuple(k),D=D,
        log_quotient=d['log'][1],log_remainder=d['log'][2],
        lp_quotient=d['lambda_prime'][1],lp_remainder=d['lambda_prime'][2],
        l0_quotient=d['lambda0'][1],l0_remainder=d['lambda0'][2],
        counts=tuple((r[0],r[3],r[4]) for r in rows),
        odd_flags=tuple(r[5] for r in rows),
    )


def corner_log_delta_decomposition(u=None,v=None,k2=None,D=None):
    """Exact decomposition Lambda'^2-Lambda0^2 = A_K*k^2 + A_D*D."""
    u=sp.Symbol('u') if u is None else sp.sympify(u)
    v=sp.Symbol('v') if v is None else sp.sympify(v)
    k2=sp.Symbol('K') if k2 is None else sp.sympify(k2)
    D=sp.Symbol('D') if D is None else sp.sympify(D)
    AK=sp.expand(u**2*v*(1-v))
    AD=sp.expand(u*v*(1-u))
    delta=sp.expand(AK*k2+AD*D)
    return {'K_coefficient':AK,'D_coefficient':AD,'expression':delta}


def _corner_one_loop_gaussian_stream(poly,n,k,shift,A,C,pole_prefix='CORNER_GAMMA'):
    """4D Wick/isotropic one-loop reduction with common pi^2 removed.

    This is the same monomial-streaming master used by the self-energy outer
    bridge.  k0=i*K0+shift, spatial components are unshifted, and the completed
    denominator is A*K_E^2+C.
    """
    poly=sp.expand(poly); pp=sp.Poly(poly,*k,domain='EX')
    out=sp.Integer(0)
    for monomial,coefficient in pp.terms():
        e0=monomial[0]
        for j0 in range(e0+1):
            if j0 % 2:
                continue
            exponents=(j0,)+monomial[1:]
            if any(ex % 2 for ex in exponents[1:]):
                continue
            rank_half=sum(exponents)//2
            gamma_arg=n-rank_half-2
            angular_num=sp.Integer(1)
            for ex in exponents:
                s=ex//2
                if s:
                    angular_num *= sp.factorial2(2*s-1)
            angular_den=sp.Integer(1)
            for j in range(rank_half):
                angular_den *= sp.Integer(4+2*j)
            angular=angular_num/angular_den
            binomial=sp.binomial(e0,j0)*sp.I**j0*shift**(e0-j0)
            gamma_factor=(sp.gamma(gamma_arg) if gamma_arg>0
                          else sp.Symbol(f'{pole_prefix}_{gamma_arg}'))
            radial=(sp.gamma(rank_half+2)*gamma_factor/sp.gamma(n)
                    *A**(-2-rank_half)*C**(2+rank_half-n))
            out += coefficient*binomial*angular*radial
    return sp.factor(out)


@dataclass(frozen=True)
class CornerRationalGaussianBridge:
    """Finite Gaussian reductions of the two rational inner-remainder streams."""
    lp_kernel: sp.Expr
    l0_kernel: sp.Expr
    lp_poles: tuple
    l0_poles: tuple
    symbols: tuple


def _corner_strip_zero_poles(expr,prefix='CORNER_GAMMA'):
    expr=sp.expand(expr); audits=[]
    for pole in sorted((s for s in expr.free_symbols if s.name.startswith(prefix)),key=lambda x:x.name):
        coeff=sp.factor(expr.coeff(pole)); audits.append((pole,coeff))
        if coeff == 0:
            expr=expr.subs(pole,0)
    return sp.factor(expr),tuple(audits)


@lru_cache(maxsize=1)
def corner_rational_gaussian_bridge() -> CornerRationalGaussianBridge:
    """Gaussian-reduce -C(k)/(2 Lambda') and +C(0)/(2 Lambda0) streams.

    The projector common-denominator quotient is used, so no spurious UV pole
    is introduced.  The returned objects are rational parameter kernels before
    the overall inner measure u du dv and physical 1/4 normalization.
    """
    q=corner_outer_common_quotients(); s=corner_outer_projector_streams()
    u,v,rho=s.u,s.v,s.rho; k=s.k
    ad,al=sp.symbols('a_d a_l', nonnegative=True)
    den=corner_outer_stream_denominators(u,v,rho,ad,al,sp.Symbol('z_inner'))

    # 1/(K D^2 Lambda') = 6 ad / M^4.  Physical inner remainder coefficient -1/2.
    lp_raw=-3*ad*_corner_one_loop_gaussian_stream(
        q.lp_quotient,4,k,den.B/den.H,den.H,den.Q/den.H
    )
    lp,lp_poles=_corner_strip_zero_poles(lp_raw)

    # Lambda0 is independent of k: 1/(K D^2)=2 ad/M^3, times +1/(2 Lambda0).
    l0_raw=ad/den.lambda0_sq*_corner_one_loop_gaussian_stream(
        q.l0_quotient,3,k,ad,sp.Integer(1),den.Q_0
    )
    l0,l0_poles=_corner_strip_zero_poles(l0_raw)
    return CornerRationalGaussianBridge(lp,l0,lp_poles,l0_poles,(u,v,rho,ad,al))


