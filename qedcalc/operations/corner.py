def corner_dimensional_radial_audit(epsilon=None) -> CornerDimensionalRadialAudit:
    """Audit the rank-two inner-vertex gamma channel in D=4-2 epsilon.

    For the radial numerator piece

        gamma^alpha /r gamma_nu /r gamma_alpha,

    symmetric D-dimensional integration gives

        <r_mu r_nu> = g_mu_nu r^2 / D,
        c(D) gamma_nu r^2,  c(D)=(D-2)^2/D.

    The normalized UV master for r^2/(r^2+L)^3, after factoring the common
    pi^(D/2), is represented at L=1 by

        J(D) = (D/4) Gamma(epsilon).

    Hence doing the gamma algebra at D=4 before the UV pole is expanded drops
    the exact local finite term

        lim_{epsilon->0} [c(D)-1] J(D) = -3/2.

    This is an audit quantity only.  It is *not* inserted as an ad-hoc corner
    correction; the next bridge must propagate it through the on-shell B*gamma
    subtraction and outer projector before any physical finite shift is claimed.
    """
    eps=sp.Symbol('epsilon', positive=True) if epsilon is None else sp.sympify(epsilon)
    D=sp.expand(4-2*eps)
    coeff=sp.cancel((D-2)**2/D)
    coeff_series=sp.series(coeff,eps,0,3)
    J=sp.gamma(eps)*D/4
    shift=sp.simplify(sp.limit((coeff-1)*J,eps,0,dir='+'))
    return CornerDimensionalRadialAudit(eps,D,coeff,coeff_series,J,shift)


