def corner_local_uv_subtractions(x=None,y=None,z=None,u=None,v=None,rho=None):
    """Local five-simplex representatives of the B gamma_rho UV subtraction."""
    x=sp.Symbol('x') if x is None else sp.sympify(x)
    y=sp.Symbol('y') if y is None else sp.sympify(y)
    z=sp.Symbol('z') if z is None else sp.sympify(z)
