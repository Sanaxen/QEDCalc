@lru_cache(maxsize=1)
def corner_physical_parameter_kernels() -> CornerPhysicalParameterKernels:
    """Insert completed H/Q forms into the compact Gaussian templates.

    These four kernels are an independent routing of the physical Eq.(42)-type
    remainder.  The historical I_K/I_kappa/I_z rational functions are not used.
    """
    t=corner_physical_gaussian_templates()
    allsyms=t.lp_template.free_symbols | t.b_template.free_symbols | t.log_n3_template.free_symbols
    by={s.name:s for s in allsyms}; S=by['CORNER_SHIFT']; A=by['CORNER_A']; C=by['CORNER_C']
    u=by['u']; v=by['v']
    rho,ad,al,z,ap=sp.symbols('rho a_d a_l z_inner a_p', positive=True)
    L0=sp.expand(u**2+rho**2*(1-u)); AA=sp.expand(u*v*(1-u*v)); BB=sp.expand(u*v*(1-u))

    # +C(k)/(2 Lambda') on K*D^2*Lambda'.
    H=sp.expand(1-al+al*AA); Bs=sp.expand(ad+al*BB)
    Q=sp.expand(Bs**2+H*((1-ad-al)*rho**2+al*L0))
    lp=sp.cancel(3*ad*t.lp_template.subs({S:Bs/H,A:H,C:Q/H}))

    # -2 f gamma/Lambda0 on K*D^2.  The -2f is already inside b_template.
    Q0=sp.expand(ad**2+(1-ad)*rho**2)
    bg=sp.cancel(2*ad/L0*t.b_template.subs({S:ad,A:1,C:Q0}))

    # log sector: (Lp-L0) int dz/Lz with exact K/D cancellation.
    AK=sp.expand(u**2*v*(1-v)); AD=sp.expand(u*v*(1-u))

    # Correct scalar-denominator cancellation.  In the Minkowski convention
    # used by the raw Eq.(42) chain, the outer scalar denominators are
    #
    #   P = rho^2-k^2,     E = -D(k).
    #
    # Hence
    #
    #   (AK*k^2+AD*D)/(P*E^2*Lz)
    #     = -AK/(E^2*Lz) - AD/(P*E*Lz)
    #       + AK*rho^2/(P*E^2*Lz).
    #
    # v0.61--v0.65 used the first two terms with the opposite sign and
    # omitted the photon-mass residual (third term).

    # Photon denominator cancels: E^2 * Lz, parameters ad1=1-al and al.
    ad1=sp.expand(1-al)
    A1=sp.expand(ad1+al*z*AA); B1=sp.expand(ad1+al*z*BB)
    C1=sp.expand(al*L0+B1**2/A1)
    lk=sp.cancel(-2*ad1*AK*t.log_n3_template.subs({S:B1/A1,A:A1,C:C1}))

    # One electron denominator cancels: P * E * Lz, simplex ap+ad+al2=1.
    al2=sp.expand(1-ap-ad)
    A2=sp.expand(ap+ad+al2*z*AA); B2=sp.expand(ad+al2*z*BB)
    C2=sp.expand(ap*rho**2+al2*L0+B2**2/A2)
    ld=sp.cancel(-2*AD*t.log_n3_template.subs({S:B2/A2,A:A2,C:C2}))

    # Finite-photon-mass residual: P * E^2 * Lz.
    # Feynman weight for powers (1,2,1) is 6*a_d.
    Hm=sp.expand(ap+ad+al2*z*AA); Bm=B2
    Cm=C2
    lm=sp.factor(6*ad*AK*rho**2*t.log_n4_template.subs({S:Bm/Hm,A:Hm,C:Cm}))

    return CornerPhysicalParameterKernels(
        lp,bg,lk,ld,lm,
        (u,v,rho,ad,al),(u,rho,ad),(u,v,rho,z,al),(u,v,rho,z,ap,ad),
        (u,v,rho,z,ap,ad)
    )


