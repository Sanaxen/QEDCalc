from functools import lru_cache


@dataclass(frozen=True)
class SelfEnergyRawBareResult:
    """Raw two-diagram magnetic reduction before on-shell subtraction.

    The result is normalized as the coefficient of ``(alpha/pi)^2``.  It is
    generated from the two explicit Dirac chains, their q-linear numerator and
    denominator variations, and the common q=0 denominator family

        D_k^3 D_kl K L.

    No stored bare coefficient polynomial is used.
    """
    integrand: sp.Expr
    numerator: sp.Expr
    Delta: sp.Expr
    F: sp.Expr
    base_term_count: int
    gaussian_sector_keys: tuple
    sample_checks: tuple


def _self_energy_explicit_gamma_data():
    I = sp.I
    zero = sp.zeros(2)
    sx = sp.Matrix([[0, 1], [1, 0]])
    sy = sp.Matrix([[0, -I], [I, 0]])
    sz = sp.Matrix([[1, 0], [0, -1]])
    g0 = sp.diag(1, 1, -1, -1)
    def gi(sig):
        return sp.Matrix.vstack(sp.Matrix.hstack(zero, sig), sp.Matrix.hstack(-sig, zero))
    gu = (g0, gi(sx), gi(sy), gi(sz))
    metric = (1, -1, -1, -1)
    gl = tuple(metric[i] * gu[i] for i in range(4))
    return gu, gl


def _self_energy_wick_component(ep, eq, a, b, c, cache):
    key = (ep, eq)
    if key in cache:
        return cache[key]
    n = ep + eq
    if n == 0:
        out = sp.Integer(1)
    elif n % 2:
        out = sp.Integer(0)
    elif ep:
        out = sp.Integer(0)
        if ep >= 2:
            out += (ep - 1) * b * _self_energy_wick_component(ep - 2, eq, a, b, c, cache)
        if eq:
            out += eq * (-c) * _self_energy_wick_component(ep - 1, eq - 1, a, b, c, cache)
        out = sp.expand(out)
    else:
        out = (eq - 1) * a * _self_energy_wick_component(0, eq - 2, a, b, c, cache)
    cache[key] = out
    return out


def _self_energy_stream_gaussian_laurent(poly, n, k, l, a, b, c, Delta, F, tk_num, tl_num):
    """Streaming two-loop Gaussian reduction with common pi^4 removed."""
    from collections import defaultdict
    variables = tuple(k) + tuple(l)
    ppoly = sp.Poly(poly, *variables)
    wick_cache = {}
    accum = defaultdict(lambda: sp.Integer(0))

    def centered_moment(exponents):
        degree = sum(exponents)
        if degree % 2:
            return sp.Integer(0), degree // 2
        value = sp.Integer(1)
        for mu in range(4):
            value *= _self_energy_wick_component(
                exponents[mu], exponents[4 + mu], a, b, c, wick_cache
            )
            if value == 0:
                return sp.Integer(0), degree // 2
        return sp.expand(value), degree // 2

    for monomial, coefficient in ppoly.terms():
        ek0, el0 = monomial[0], monomial[4]
        base = list(monomial)
        for jk in range(ek0 + 1):
            ck = sp.binomial(ek0, jk) * sp.I**jk * tk_num**(ek0 - jk)
            dk = ek0 - jk
            for jl in range(el0 + 1):
                cl = sp.binomial(el0, jl) * sp.I**jl * tl_num**(el0 - jl)
                dl = el0 - jl
                exponents = list(base)
                exponents[0] = jk
                exponents[4] = jl
                wick, rank_half = centered_moment(tuple(exponents))
                if wick == 0:
                    continue
                gamma_arg = n - 4 - rank_half
                if gamma_arg <= 0:
                    gamma_factor = sp.Symbol(f"GAMMA_{gamma_arg}")
                else:
                    gamma_factor = sp.gamma(gamma_arg)
                prefactor = gamma_factor / (sp.gamma(n) * 2**rank_half)
                delta_power = n - 6 - 2 * rank_half - dk - dl
                f_power = 4 + rank_half - n
                accum[(delta_power, f_power)] += coefficient * ck * cl * wick * prefactor
    return {key: sp.expand(value) for key, value in accum.items() if value != 0}


def _self_energy_raw_projector_polynomials():
    """Generate q=0 and q-linear magnetic numerators for both raw diagrams.

    The chain order is the one discovered in the raw left/right Feynman inputs.
    At q=0 the incoming electron is at rest and q points along +x.  The spinor
    correction is the component form

        a2 = N2^(1)[0,0] - 1/2 N2^(0)[3,0],
        a0 = N0^(0)[0,0],

    so the base magnetic numerator is 2 i a2 - a0.
    """
    I = sp.I
    gu, gl = _self_energy_explicit_gamma_data()
    ident = sp.eye(4)
    k = sp.symbols("k0:4")
    l = sp.symbols("l0:4")

    def slash(v):
        return gu[0]*v[0] - gu[1]*v[1] - gu[2]*v[2] - gu[3]*v[3]

    p = (sp.Integer(1), 0, 0, 0)
    qslash = -gu[1]
    Rk = ident + slash(tuple(p[i] - k[i] for i in range(4)))
    Rkl = ident + slash(tuple(p[i] - k[i] - l[i] for i in range(4)))

    def chain(diagram, mu):
        n0 = sp.zeros(4)
        nq = sp.zeros(4)
        for rho_idx in range(4):
            for alpha_idx in range(4):
                if diagram == "right":
                    n0 += gu[rho_idx]*Rk*gl[mu]*Rk*gu[alpha_idx]*Rkl*gl[alpha_idx]*Rk*gl[rho_idx]
                    nq += gu[rho_idx]*qslash*gl[mu]*Rk*gu[alpha_idx]*Rkl*gl[alpha_idx]*Rk*gl[rho_idx]
                else:
                    n0 += gu[rho_idx]*Rk*gu[alpha_idx]*Rkl*gl[alpha_idx]*Rk*gl[mu]*Rk*gl[rho_idx]
                    nq += gu[rho_idx]*qslash*gu[alpha_idx]*Rkl*gl[alpha_idx]*Rk*gl[mu]*Rk*gl[rho_idx]
                    nq += gu[rho_idx]*Rk*gu[alpha_idx]*qslash*gl[alpha_idx]*Rk*gl[mu]*Rk*gl[rho_idx]
                    nq += gu[rho_idx]*Rk*gu[alpha_idx]*Rkl*gl[alpha_idx]*qslash*gl[mu]*Rk*gl[rho_idx]
        return n0, nq

    bra0 = sp.Matrix([[1, 0, 0, 0]])
    braq = sp.Matrix([[0, 0, 0, -sp.Rational(1, 2)]])
    ket = sp.Matrix([1, 0, 0, 0])
    base = sp.Integer(0)
    transverse_zero = {}
    for diagram in ("left", "right"):
        n00, _ = chain(diagram, 0)
        n20, n2q = chain(diagram, 2)
        m00 = sp.expand((bra0*n00*ket)[0])
        m20 = sp.expand((bra0*n20*ket)[0])
        m21 = sp.expand((braq*n20*ket)[0] + (bra0*n2q*ket)[0])
        base += sp.expand(2*I*m21 - m00)
        transverse_zero[diagram] = m20
    return k, l, sp.expand(base), transverse_zero


@lru_cache(maxsize=1)
def self_energy_raw_bare_parametric_integrand() -> SelfEnergyRawBareResult:
    """Reconstruct the raw two-diagram bare magnetic parameter integrand.

    The q=0 denominator powers are D_k^3 D_kl K L.  The q derivative gives
    three distinct D^-7 streams:

    * right insertion: +2 (p-k).q / D_k,
    * left insertion, two D_k' factors: +4 (p-k).q / D_k,
    * left insertion, one D_kl' factor: +2 (p-k-l).q / D_kl.

    Each stream receives its own exact Feynman-parameter Gamma prefactor before
    the common Gaussian reduction.  The final 1/16 converts the raw e^4/(2pi)^8
    normalization to the coefficient multiplying (alpha/pi)^2.
    """
    from collections import defaultdict
    x, y, u, v, rho = sp.symbols("x y u v rho")
    a = x + y + u
    b = y + v
    c = y
    r = x + y
    s = y
    Delta = sp.expand(a*b - c**2)
    W = sp.expand(b*r**2 - 2*c*r*s + a*s**2)
    F = sp.expand(W + rho**2*(u+v)*Delta)
    tk_num = sp.expand(b*r - c*s)
    tl_num = sp.expand(a*s - c*r)

    k, l, base, m20 = _self_energy_raw_projector_polynomials()
    blocks = (
        # Gamma(6)/(Gamma(3)...) = 60, measure x^2.
        (60*x**2, _self_energy_stream_gaussian_laurent(base, 6, k, l, a, b, c, Delta, F, tk_num, tl_num)),
        # right D_k derivative: 2 k_x, Gamma(7)/Gamma(4)=120 x^3.
        (120*x**3, _self_energy_stream_gaussian_laurent(4*sp.I*m20["right"]*k[1], 7, k, l, a, b, c, Delta, F, tk_num, tl_num)),
        # left two D_k' factors: 4 k_x.
        (120*x**3, _self_energy_stream_gaussian_laurent(8*sp.I*m20["left"]*k[1], 7, k, l, a, b, c, Delta, F, tk_num, tl_num)),
        # left D_kl' derivative, powers D_k^3 D_kl^2: Gamma(7)/(Gamma(3)Gamma(2))=360 x^2 y.
        (360*x**2*y, _self_energy_stream_gaussian_laurent(4*sp.I*m20["left"]*(k[1]+l[1]), 7, k, l, a, b, c, Delta, F, tk_num, tl_num)),
    )
    accum = defaultdict(lambda: sp.Integer(0))
    sector_keys = set()
    for measure, block in blocks:
        for key, value in block.items():
            sector_keys.add(key)
            accum[key] += sp.expand(measure*value)

    common = sp.Integer(0)
    for (dpow, fpow), coefficient in accum.items():
        common += coefficient * Delta**(dpow+4) * F**(fpow+2)
    common = sp.expand(common)
    # Any apparent Gamma(0) tensor pieces must cancel in the complete pair.
    for symbol in tuple(common.free_symbols):
        if symbol.name.startswith("GAMMA_"):
            coeff = sp.expand(common).coeff(symbol)
            if sp.simplify(coeff) != 0:
                raise ValueError(f"uncancelled apparent Gaussian pole {symbol}: {coeff}")
            common = common.subs(symbol, 0)
    # e^4/(2pi)^8 with two Wick rotations and common pi^4 -> (alpha/pi)^2 / 16.
    numerator = sp.factor(common / 16)
    integrand = sp.cancel(numerator / (Delta**4 * F**2))

    # Regression-only exact checkpoints from the independently archived derivation.
    checkpoints = (
        ({x:1, y:2, u:3, v:4, rho:sp.Rational(1,5)}, sp.Rational(9637425,162363867136)),
        ({x:2, y:1, u:1, v:3, rho:sp.Rational(1,7)}, sp.Rational(1389346,12567976875)),
        ({x:1, y:1, u:1, v:1, rho:0}, sp.Rational(167,30625)),
    )
    checks = tuple(sp.simplify(integrand.subs(subs)-expected) for subs, expected in checkpoints)
    return SelfEnergyRawBareResult(
        integrand=integrand,
        numerator=numerator,
        Delta=Delta,
        F=F,
        base_term_count=len(sp.Poly(base, *(tuple(k)+tuple(l))).terms()),
        gaussian_sector_keys=tuple(sorted(sector_keys)),
        sample_checks=checks,
    )

@dataclass(frozen=True)
class SelfEnergyRawUVAudit:
    coefficient_xy: sp.Expr
    coefficient_x: sp.Expr
    coefficient_rho0: sp.Expr
    archived_difference: sp.Expr


@lru_cache(maxsize=1)
def self_energy_raw_uv_subdivergence() -> SelfEnergyRawUVAudit:
    """Extract the logarithmic self-energy UV sub-sector from the generated bare pair.

    Uses y=tY, v=t(1-Y), x=(1-t)X, u=(1-t)(1-X).  Since the simplex
    Jacobian contributes t(1-t), a t^-2 bare integrand gives dt/t.
    """
    raw = self_energy_raw_bare_parametric_integrand()
    x,y,u,v,rho = sp.symbols("x y u v rho")
    t,X,Y = sp.symbols("t X Y", positive=True)
    mapped = sp.cancel(raw.integrand.subs({
        y:t*Y,
        v:t*(1-Y),
        x:(1-t)*X,
        u:(1-t)*(1-X),
    }))
    coefficient_xy = sp.factor(sp.limit(t**2*mapped, t, 0))
    coefficient_x = sp.factor(sp.integrate(coefficient_xy, (Y,0,1)))
    expected = sp.factor(
        X**2*(X-1)*(3*X**3-4*X**2*rho**2-5*X**2+14*X*rho**2-10*rho**2)
        /(4*(X**2+rho**2*(1-X))**2)
    )
    return SelfEnergyRawUVAudit(
        coefficient_xy=coefficient_xy,
        coefficient_x=coefficient_x,
        coefficient_rho0=sp.factor(coefficient_x.subs(rho,0)),
        archived_difference=sp.factor(coefficient_x-expected),
    )

