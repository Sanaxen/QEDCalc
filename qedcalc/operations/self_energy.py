def finite_b_integrated_kernel_derived(a, z, q):
    r"""Regenerate the b integral directly from G_A by Y=ab+q^2 z(1-a).

    This avoids using the stored C0/C1 formula.  The transformed integrand is a
    finite Laurent polynomial in Y with only Y^0, Y^-1, Y^-2 terms, so the
    result is generated by monomial integration and one logarithm.
    """
    a, z, q = map(sp.sympify, (a, z, q))
    b, Y = sp.symbols("b Y", positive=True)
    G = finite_four_parameter_integrand(a, z, b, q)
    C = sp.simplify(q**2 * z * (1 - a))
    numerator = sp.simplify(G * (a * b + C) ** 2)
    transformed = sp.expand(numerator.subs(b, (Y - C) / a) / (a * Y**2))
    poly = sp.Poly(sp.expand(transformed * Y**2), Y)
    Y0 = C
    Y1 = sp.simplify(a * q + C)
    Ldummy = sp.Symbol("L_b")
    result = 0
    for (exp,), coeff in poly.terms():
        power = exp - 2
        if power == -1:
            result += coeff * Ldummy
        else:
            result += coeff * (Y1 ** (power + 1) - Y0 ** (power + 1)) / sp.Integer(power + 1)
    result = sp.factor(sp.simplify(result))
    physical_log = sp.log(1 + a / (q * z * (1 - a)))
    return result.subs(Ldummy, physical_log)


def self_energy_I0(c):
    """Elementary z integral int_0^1 log(1+c/z) dz."""
    c = sp.sympify(c)
    return sp.simplify((1 + c) * sp.log(1 + c) - c * sp.log(c))


def self_energy_I1(c):
    """Elementary z integral int_0^1 z log(1+c/z) dz."""
    c = sp.sympify(c)
    return sp.simplify(c / 2 + sp.Rational(1, 2) * ((1 - c**2) * sp.log(1 + c) + c**2 * sp.log(c)))


def finite_z_integrated_kernel_derived(a, q):
    r"""Regenerate the z integral of the generated b kernel using I0 and I1."""
    a, q = map(sp.sympify, (a, q))
    z = sp.Symbol("z", positive=True)
    # Preserve the unique logarithm with a dummy symbol so its z-linear
    # coefficient can be extracted without branch-changing simplification.
    Ldummy = sp.Symbol("L_z")
    bkernel = finite_b_integrated_kernel_derived(a, z, q)
    physical_log = sp.log(1 + a / (q * z * (1 - a)))
    canonical = sp.expand(bkernel.xreplace({physical_log: Ldummy}))
    # factor()/simplify() may have rewritten the log argument; if so rebuild
    # the same b integral with the dummy logarithm through coefficient matching.
    if not canonical.has(Ldummy):
        # The generated closed form is known to contain one log(Y1/Y0). Replace
        # any log whose argument simplifies to the physical ratio.
        for atom in list(canonical.atoms(sp.log)):
            if sp.simplify(atom.args[0] - (1 + a / (q * z * (1 - a)))) == 0:
                canonical = canonical.xreplace({atom: Ldummy})
    if not canonical.has(Ldummy):
        # Deterministic fallback: derive the b integral again but keep log dummy.
        b, Y = sp.symbols("b Y", positive=True)
        G = finite_four_parameter_integrand(a, z, b, q)
        C = sp.simplify(q**2 * z * (1 - a))
        numerator = sp.simplify(G * (a * b + C) ** 2)
        transformed = sp.expand(numerator.subs(b, (Y - C) / a) / (a * Y**2))
        polyY = sp.Poly(sp.expand(transformed * Y**2), Y)
        Y0, Y1 = C, sp.simplify(a*q + C)
        canonical = 0
        for (exp,), coeff in polyY.terms():
            power = exp - 2
            if power == -1:
                canonical += coeff * Ldummy
            else:
                canonical += coeff * (Y1**(power+1)-Y0**(power+1))/sp.Integer(power+1)
        canonical = sp.expand(canonical)

    coeff_L = sp.expand(canonical).coeff(Ldummy)
    constant = sp.simplify(sp.expand(canonical) - coeff_L * Ldummy)
    pz = sp.Poly(sp.expand(coeff_L), z)
    if pz.degree() > 1:
        raise ValueError("Unexpected z degree in self-energy logarithm coefficient")
    c = sp.simplify(a / (q * (1 - a)))
    result = (
        pz.coeff_monomial(z) * self_energy_I1(c)
        + pz.coeff_monomial(1) * self_energy_I0(c)
        + constant
    )
    return sp.simplify(result)


def _self_energy_real_log_rewrite(expr, a, q):
    """Put z-integrated logarithms on the real 0<a,q<1 branch."""
    expr = sp.sympify(expr)
    c = a / (q * (1 - a))
    logc = sp.log(a) - sp.log(q) - sp.log(1 - a)
    log1c = sp.log(a + q * (1 - a)) - sp.log(q) - sp.log(1 - a)
    return sp.expand(expr.xreplace({sp.log(c): logc, sp.log(1 + c): log1c}))


def finite_one_variable_kernel_derived(a):
    """Regenerate F(a) by analytic z integration followed by q integration."""
    a = sp.sympify(a)
    q = sp.Symbol("q", positive=True)
    zexpr = finite_z_integrated_kernel_derived(a, q)
    zexpr = _self_energy_real_log_rewrite(zexpr, a, q)
    result = sp.integrate(zexpr, (q, 0, 1))
    # SymPy may display real positive arguments through algebraically equivalent
    # complex-log continuations. expand_log(force=True) returns the interval form.
    result = sp.expand_log(result, force=True)
    # Remove cancelling explicit i*pi terms generated by branch bookkeeping.
    result = sp.simplify(sp.expand_complex(result).as_real_imag()[0]) if result.has(sp.I) else sp.simplify(result)
    # Physical integration domain is 0<a<1.  SymPy may retain Abs(a-1)
    # after real-part extraction; on this domain it is exactly 1-a.
    result = result.subs(sp.Abs(a - 1), 1 - a).subs(sp.Abs(1 - a), 1 - a)
    return sp.simplify(result)


def finite_one_variable_kernel_residual(a):
    """Regression-only difference from the previously audited closed F(a)."""
    a = sp.sympify(a)
    return sp.simplify(
        sp.expand_log(finite_one_variable_kernel_derived(a), force=True)
        - sp.expand_log(finite_one_variable_kernel(a), force=True)
    )


def self_energy_standard_integrals():
    """Generate the elementary/Euler-sum constants used in the final a integral."""
    zeta2 = sp.simplify(sp.zeta(2))
    # General identities: int_0^1 x^n log x dx=-1/(n+1)^2 and
    # int_0^1 x^n log(1-x) dx=-H_{n+1}/(n+1).
    power_log_x_1 = -sp.Rational(1, 4)
    power_log_x_0 = -sp.Integer(1)
    power_log_1mx_1 = -sp.harmonic(2) / 2
    power_log_1mx_0 = -sp.harmonic(1)
    log_x_over_1mx = -zeta2
    log_1mx_over_x = -zeta2
    # The endpoint-safe pair telescopes: -sum_{n=2}^ 1/[n(n-1)] = -1.
    endpoint_pair = -sp.summation(1 / (sp.Symbol('n', integer=True, positive=True) * (sp.Symbol('n', integer=True, positive=True) - 1)), (sp.Symbol('n', integer=True, positive=True), 2, sp.oo))
    return {
        "x_log_x": sp.simplify(power_log_x_1),
        "log_x": sp.simplify(power_log_x_0),
        "log_x_over_1mx": sp.simplify(log_x_over_1mx),
        "x_log_1mx": sp.simplify(power_log_1mx_1),
        "log_1mx": sp.simplify(power_log_1mx_0),
        "log_1mx_over_x": sp.simplify(log_1mx_over_x),
        "endpoint_pair": sp.simplify(endpoint_pair),
    }


def finite_part_analytic_derived():
    """Assemble A_A(0) from generated standard integrals, not a stored final value."""
    I = self_energy_standard_integrals()
    ln_a = sp.simplify(
        sp.Rational(1, 2) * I["x_log_x"]
        - sp.Rational(1, 6) * I["log_x"]
        + sp.Rational(1, 6) * I["log_x_over_1mx"]
    )
    ln_1ma = sp.simplify(
        -sp.Rational(1, 2) * I["x_log_1mx"]
        + sp.Rational(1, 6) * I["log_1mx"]
        + sp.Rational(1, 6) * I["log_1mx_over_x"]
    )
    endpoint = sp.simplify(sp.Rational(1, 6) * I["endpoint_pair"])
    rational = sp.simplify(sp.Rational(1, 4) * sp.Rational(1, 2) - sp.Rational(1, 4))
    total = sp.simplify(ln_a + ln_1ma + endpoint + rational)
    return {
        "ln_a": ln_a,
        "ln_one_minus_a": ln_1ma,
        "endpoint_pair": endpoint,
        "rational": rational,
        "total": total,
    }


def self_energy_ir_asymptotic_derived(rho):
    r"""Derive H_B = log(rho)+1/2 from the factorized one-loop limits.

    A^(1)(rho)->int_0^1(1-X)dX=1/2.  For J(rho), subtract
    a/(a^2+rho^2); the singular integral gives -log(rho), while the
    rho->0 remainder is simply int_0^1(-a)da=-1/2.
    """
    rho = sp.sympify(rho)
    X, a = sp.symbols("X a", positive=True)
    A1 = sp.integrate(1 - X, (X, 0, 1))
    J_log_coeff = -sp.Integer(1)  # J contains -log(rho)
    J_finite = sp.integrate(-a, (a, 0, 1))
    J_asym = sp.simplify(J_log_coeff * sp.log(rho) + J_finite)
    B = sp.simplify(-2 * A1 * J_asym)
    return {
        "A1_limit": sp.simplify(A1),
        "J_log_coefficient": J_log_coeff,
        "J_finite": sp.simplify(J_finite),
        "J_asymptotic": J_asym,
        "B_asymptotic": B,
    }


def total_self_energy_coefficient_derived(rho):
    """Assemble the two-diagram self-energy coefficient from independently derived A and B."""
    rho = sp.sympify(rho)
    return sp.simplify(self_energy_ir_asymptotic_derived(rho)["B_asymptotic"] + finite_part_analytic_derived()["total"])


def self_energy_finite_audit(rho=None):
    if rho is None:
        rho = sp.Symbol("rho", positive=True)
    a, z, q = sp.symbols("a z q", positive=True)
    bint = finite_b_integrated_kernel_derived(a, z, q)
    zint = finite_z_integrated_kernel_derived(a, q)
    one = finite_one_variable_kernel_derived(a)
    residual = finite_one_variable_kernel_residual(a)
    finite = finite_part_analytic_derived()
    ir = self_energy_ir_asymptotic_derived(rho)
    total = total_self_energy_coefficient_derived(rho)
    return SelfEnergyFiniteAudit(
        bint, zint, one, residual,
        finite["ln_a"], finite["ln_one_minus_a"], finite["endpoint_pair"],
        finite["rational"], finite["total"], ir["A1_limit"],
        ir["J_log_coefficient"], ir["J_finite"], ir["B_asymptotic"], total,
    )

