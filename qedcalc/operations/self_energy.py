@dataclass(frozen=True)
class SelfEnergyRenormalizedOuterResult:
    """Independent reconstruction of the finite H_A four-parameter kernel.

    The route starts from the on-shell-renormalized self-energy block after the
    logarithm has been rationalized.  At rho=0 the H_A insertion is

        a(1-a) S(r) [4 - 2(1-a) /r] (1+/r) / Q,
        Q = a^2 + z a(1-a) D,   D = 1-r^2.

    It is inserted on the left and right of the outer one-loop magnetic vertex,
    projected at first order in q, Feynman-parameterized as K D^2 Q, and
    Gaussian-reduced before the (t,e)->(q,b) map is applied.
    """
    old_integrand: sp.Expr
    transformed_integrand: sp.Expr
    generated_GA: sp.Expr
    checkpoint_residual: sp.Expr
    normalization_factor: sp.Expr
    denominator_D_stream: sp.Expr
    denominator_Q_stream: sp.Expr
    projector_term_counts: tuple


def self_energy_sigmaR_finite_integrand_structure(a, r2, m=1, photon_mass=0):
    """Return the finite on-shell-renormalized Sigma_R integrand structure.

    This is the finite integrand inside alpha/(4*pi) int da after UV constants
    cancel, before the logarithm is rationalized.  ``rslash`` is left as a
    commuting placeholder because this helper is for the algebraic structure;
    the explicit Dirac realization is used by the outer-projector bridge.
    """
    a, r2, m, photon_mass = map(sp.sympify, (a, r2, m, photon_mass))
    rslash = sp.Symbol("rslash", commutative=False)
    Delta = self_energy_delta(a, r2, m, photon_mass)
    Delta0 = self_energy_delta0(a, m, photon_mass)
    log_part = (4*m - 2*(1-a)*rslash) * sp.log(Delta/Delta0)
    ct_part = 4*m**2*(rslash-m)*a*(1-a)*(1+a)/Delta0
    return log_part + ct_part


def self_energy_HA_scalar_denominator(a, z, D, m=1, photon_mass=0):
    """Rationalized H_A denominator Q in terms of D=m^2-r^2."""
    a, z, D, m, photon_mass = map(sp.sympify, (a,z,D,m,photon_mass))
    Delta0 = self_energy_delta0(a, m, photon_mass)
    return sp.expand(Delta0 + z*a*(1-a)*D)


def _self_energy_one_loop_gaussian_stream(poly, n, k, shift, A, C):
    """One-loop 4D isotropic Gaussian reduction with the common pi^2 removed.

    The Wick-completed loop momentum is k0 = i*K0 + shift, while spatial
    components are unchanged.  ``A*K_E^2 + C`` is the completed denominator.
    The implementation streams monomials and never forms a large shifted
    polynomial.
    """
    poly = sp.expand(poly)
    pp = sp.Poly(poly, *k)
    out = sp.Integer(0)
    for monomial, coefficient in pp.terms():
        e0 = monomial[0]
        for j0 in range(e0 + 1):
            if j0 % 2:
                continue
            exponents = (j0,) + monomial[1:]
            if any(ex % 2 for ex in exponents[1:]):
                continue
            rank_half = sum(exponents) // 2
            gamma_arg = n-rank_half-2
            angular_num = sp.Integer(1)
            for ex in exponents:
                s = ex // 2
                if s:
                    angular_num *= sp.factorial2(2*s - 1)
            angular_den = sp.Integer(1)
            for j in range(rank_half):
                angular_den *= sp.Integer(4 + 2*j)
            angular = angular_num / angular_den
            binomial = sp.binomial(e0, j0) * sp.I**j0 * shift**(e0-j0)
            gamma_factor = sp.gamma(gamma_arg) if gamma_arg > 0 else sp.Symbol(f"HA_GAMMA_{gamma_arg}")
            radial = (
                sp.gamma(rank_half+2) * gamma_factor / sp.gamma(n)
                * A**(-2-rank_half) * C**(2+rank_half-n)
            )
            out += coefficient * binomial * angular * radial
    return sp.factor(out)


def _self_energy_HA_projector_polynomials(a):
    """Build the left/right H_A magnetic projector polynomials at O(q)."""
    a = sp.sympify(a)
    gu, gl = _self_energy_explicit_gamma_data()
    ident = sp.eye(4)
    k = sp.symbols("hk0:4")

    def slash(v):
        return gu[0]*v[0] - gu[1]*v[1] - gu[2]*v[2] - gu[3]*v[3]

    p = (sp.Integer(1), 0, 0, 0)
    qslash = -gu[1]
    r = tuple(p[i]-k[i] for i in range(4))
    R = ident + slash(r)
    Cmat = 4*ident - 2*(1-a)*slash(r)
    Hnum = R*Cmat*R
    Hq = qslash*Cmat*R + R*(-2*(1-a)*qslash)*R + R*Cmat*qslash

    def chain(diagram, mu):
        n0 = sp.zeros(4)
        nq = sp.zeros(4)
        for rho in range(4):
            if diagram == "right":
                n0 += gu[rho]*R*gl[mu]*Hnum*gl[rho]
                nq += gu[rho]*qslash*gl[mu]*Hnum*gl[rho]
            else:
                n0 += gu[rho]*Hnum*gl[mu]*R*gl[rho]
                nq += gu[rho]*Hq*gl[mu]*R*gl[rho]
        return n0, nq

    bra0 = sp.Matrix([[1,0,0,0]])
    braq = sp.Matrix([[0,0,0,-sp.Rational(1,2)]])
    ket = sp.Matrix([1,0,0,0])
    base = {}
    transverse_zero = {}
    counts = []
    for diagram in ("right", "left"):
        n00, _ = chain(diagram, 0)
        n20, n2q = chain(diagram, 2)
        m00 = sp.expand((bra0*n00*ket)[0])
        m20 = sp.expand((bra0*n20*ket)[0])
        m21 = sp.expand((braq*n20*ket)[0] + (bra0*n2q*ket)[0])
        base[diagram] = sp.expand(2*sp.I*m21 - m00)
        transverse_zero[diagram] = m20
        counts.append((diagram, len(sp.Poly(base[diagram], *k).terms()), len(sp.Poly(m20, *k).terms())))
    return k, base, transverse_zero, tuple(counts)


@lru_cache(maxsize=1)
def self_energy_renormalized_outer_to_GA() -> SelfEnergyRenormalizedOuterResult:
    """Reconstruct G_A from Sigma_R/H_A and the two outer vertex insertions.

    No stored G_A polynomial participates in the generation.  The historical
    ``finite_four_parameter_integrand`` is used only at the final line as an
    exact regression checkpoint.
    """
    a,z,t,e = sp.symbols("a z t e", positive=True)
    h = z*a*(1-a)
    As = sp.Symbol("A_HA", positive=True)
    Cs = sp.Symbol("C_HA", positive=True)
    Qs = sp.Symbol("q_HA", positive=True)

    k, base, m20, counts = _self_energy_HA_projector_polynomials(a)

    # Feynman parameters for K^1 D^2 Q^1: weights (1-t-e, t, e).
    # After square completion A=1-e+h e and shift=(t+h e)/A.
    pieces = []
    for diagram in ("right", "left"):
        pieces.append(6*t*_self_energy_one_loop_gaussian_stream(base[diagram], 4, k, Qs, As, Cs))

    # q-linear denominator streams are retained explicitly.  Their symmetric
    # Gaussian reductions vanish, which is itself a useful projector check.
    d_stream = sp.Integer(0)
    for diagram in ("right", "left"):
        d_stream += 12*t**2*_self_energy_one_loop_gaussian_stream(
            4*sp.I*m20[diagram]*k[1], 5, k, Qs, As, Cs
        )
    q_stream = 24*t*e*_self_energy_one_loop_gaussian_stream(
        4*sp.I*h*m20["left"]*k[1], 5, k, Qs, As, Cs
    )

    old = sp.factor(a*(1-a)*(sum(pieces) + d_stream + q_stream))
    for pole in tuple(old.free_symbols):
        if pole.name.startswith("HA_GAMMA_"):
            coeff = sp.factor(sp.expand(old).coeff(pole))
            if coeff != 0:
                raise ValueError(f"uncancelled H_A Gaussian pole {pole}: {coeff}")
            old = old.subs(pole, 0)
    old = sp.factor(old)

    # Detailed-derivation map.  Db=h+b(1-h), e=b/Db, A=h/Db,
    # t=h(q-b)/Db, and the completed denominator is
    # C = a[ab+z(1-a)q^2]/Db.
    q,b = sp.symbols("q b", positive=True)
    Db = h + b*(1-h)
    substitutions = {
        As: h/Db,
        Qs: q,
        e: b/Db,
        t: h*(q-b)/Db,
        Cs: a*(a*b + z*(1-a)*q**2)/Db,
    }
    jacobian = h**2/Db**3
    transformed_raw = sp.factor(sp.cancel(old.subs(substitutions)*jacobian))

    # One outer Wick rotation plus e^4/(2pi)^8 -> (alpha/pi)^2 convention.
    normalization = -sp.Rational(1,16)
    generated = sp.factor(sp.cancel(normalization*transformed_raw))
    checkpoint = finite_four_parameter_integrand(a,z,b,q)
    residual = sp.factor(sp.cancel(generated-checkpoint))
    return SelfEnergyRenormalizedOuterResult(
        old_integrand=old,
        transformed_integrand=transformed_raw,
        generated_GA=generated,
        checkpoint_residual=residual,
        normalization_factor=normalization,
        denominator_D_stream=sp.factor(d_stream),
        denominator_Q_stream=sp.factor(q_stream),
        projector_term_counts=counts,
    )

